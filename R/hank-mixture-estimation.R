#' Phase-2 structural joint (macro-KF + reweighting) recovery driver
#'
#' The Phase-2 companion to \code{\link{hank_phase1_joint_gate}}: replaces
#' Wave-1's noiseless clean-IRF-path macro proxy
#' (\code{\link{hank_macro_loss}}) with the REALISTIC structural macro
#' likelihood -- a Kalman filter (\code{\link{hank_mixture_kf_loglik}}) on a
#' synthetic macro time series of finite length \code{T_data}
#' (\code{\link{hank_mixture_simulate}}) -- while reusing the IDENTICAL
#' reweighting-side construction (\code{\link{.hank_phase0_survey}},
#' \code{\link{hank_reweight_metric}}, \code{\link{hank_reweighting_loss}}) as
#' Phase-0/Phase-1. For each \code{T_data} in \code{T_data_grid} it: (a)
#' builds the TRUTH mixture model and simulates a macro series of that
#' length; (b) generates the synthetic survey net-reweighting \code{dD_hat}
#' and its proper GLS metric \code{W}; (c) scores a \code{(centre, spread)}
#' grid of candidate mixtures against three objectives --
#' \code{rho_KF = -hank_mixture_kf_loglik(...)} (macro-alone, as a LOSS: the
#' Kalman filter returns a log-LIKELIHOOD, higher is better, so it is
#' NEGATED here to match the loss convention that lower is better, shared by
#' the other two surfaces), \code{rho_rw = hank_reweighting_loss(...)}
#' (reweight-alone), and \code{joint = rho_KF + lambda * rho_rw}.
#'
#' This function performs the MECHANICS only, mirroring
#' \code{\link{hank_phase0_reweight_gate}} / \code{\link{hank_phase1_joint_gate}}'s
#' convention: it returns the raw grids and per-\code{T_data} argmins without
#' computing or asserting any verdict on whether macro, reweighting, or the
#' joint objective "recovers" the truth -- that judgment is left to the
#' caller/orchestrator.
#'
#' \strong{Measurement-error choice}: for each simulated \code{T_data} series,
#' \code{me_variance} is set to \code{(me_frac * sd(column))^2} PER OBSERVABLE
#' COLUMN of that simulated series (i.e. a fixed fraction of the realized
#' series' own variation, analogous to \code{hank_phase1_joint_gate}'s
#' \code{sigma_macro_frac} convention) -- a simple scale-invariant way to
#' inject "the macro series is observed with some noise" without hand-picking
#' absolute noise units per observable. Because
#' \code{\link{hank_kalman_loglik}}/\code{\link{hank_mixture_kf_loglik}} take
#' a single scalar \code{me_variance} (one measurement-error variance shared
#' across observables, not a per-observable vector), the LARGER of the two
#' per-observable \code{me_variance} values is used, so the shared scalar is never
#' smaller than what either observable's own noise fraction would imply
#' (conservative: avoids an under-dispersed, potentially singular effective
#' covariance for the noisier observable).
#'
#' \strong{Truth parameterization} (as in
#' \code{\link{hank_phase0_reweight_gate}}): with \code{centre* = mean(betas)}
#' and \code{spread* = diff(betas)/2}, keep \code{centre_grid + spread_grid <
#' 1} (i.e. every candidate \code{beta = centre -+ spread < 1}) to avoid EGM
#' non-convergence at/above the discounting boundary.
#'
#' @param betas Length-2 truth discount factors; \code{centre* = mean(betas)},
#'   \code{spread* = diff(betas)/2}.
#' @param omega Length-2 truth mixture weights (non-negative, sum to 1).
#' @param n_e,n_a,amax Household grid size/extent (shared truth + candidate).
#' @param alpha,delta Capital share and depreciation.
#' @param Z Steady-state TFP (default 1).
#' @param T_h Integer GE/impulse-response horizon (shared by the macro-KF
#'   state space and the reweighting Jacobians).
#' @param shock_spec List \code{list(rho, sigma)}: the AR(1) TFP shock driving
#'   the macro-KF side (the mixture model's single exogenous shock \code{"Z"};
#'   see \code{\link{hank_mixture_ks_model}}).
#' @param me_frac Fraction of each simulated series' own column standard
#'   deviation used to set the Kalman filter's measurement-error variance
#'   (see Details).
#' @param N_survey Sample size drawn for EACH synthetic survey (pre- and
#'   post-shock; passed to \code{\link{.hank_phase0_survey}}).
#' @param T_data_grid Integer vector: the macro time-series lengths to sweep.
#' @param centre_grid,spread_grid Numeric vectors: the grid of candidate
#'   \code{centre}/\code{spread} mixture calibrations to score (kept
#'   \code{centre + spread < 1}; see Details).
#' @param lambda Non-negative scalar weight on the reweighting loss in the
#'   joint objective \code{joint = rho_KF + lambda * rho_rw}.
#' @param seed RNG seed for the synthetic sampling (macro series simulation,
#'   survey draws, and design weights).
#'
#' @return A list with:
#'   \item{T_data_grid}{As passed in.}
#'   \item{centre_grid,spread_grid}{The grids as passed in.}
#'   \item{truth}{\code{list(centre, spread)} at the truth calibration.}
#'   \item{per_T}{A list, one entry per \code{T_data_grid} value, each a list
#'     with \code{T_data}, the three grid surfaces \code{rho_KF, rho_rw,
#'     joint} (each \code{length(centre_grid) x length(spread_grid)}), and
#'     \code{argmin_KF, argmin_rw, argmin_joint} (each
#'     \code{list(centre, spread)} at that surface's grid argmin).}
#' @seealso \code{\link{hank_mixture_kf_loglik}}, \code{\link{hank_mixture_simulate}},
#'   \code{\link{hank_phase1_joint_gate}}, \code{\link{hank_reweighting_loss}}
#' @keywords internal
#' @export
hank_phase2_recovery <- function(betas = c(0.95, 0.98), omega = c(0.5, 0.5),
                                  n_e = 3L, n_a = 50L, amax = 60,
                                  alpha = 0.36, delta = 0.025, Z = 1,
                                  T_h = 20L,
                                  shock_spec = list(rho = 0.9, sigma = 0.007),
                                  me_frac = 0.1, N_survey = 5000L,
                                  T_data_grid = c(100L, 200L, 400L),
                                  centre_grid, spread_grid,
                                  lambda = 1, seed = 1L) {
  if (length(betas) != 2L) stop("hank_phase2_recovery(): 'betas' must have length 2.")
  if (!is.numeric(lambda) || length(lambda) != 1L || !is.finite(lambda) || lambda < 0)
    stop("hank_phase2_recovery(): 'lambda' must be a single non-negative finite number.")
  set.seed(seed)

  inc <- hank_income_rouwenhorst(rho = 0.9, sigma = 0.7, n = n_e)
  ag  <- hank_asset_grid(amax = amax, n = n_a, amin = 0)
  observables  <- c("C", "K")
  shock_specs  <- list(Z = list(rho = shock_spec$rho, sigma = shock_spec$sigma))

  ## ---- TRUTH mixture (shared reweighting side, Phase-0/1 machinery) -----
  centre_star <- mean(betas); spread_star <- diff(betas) / 2
  mks_truth   <- hank_mixture_ks_steady(ag, inc$Pi, inc$e, betas, omega,
                                         eis = 1, alpha = alpha, delta = delta, Z = Z)
  model_truth <- hank_mixture_ks_model(mks_truth, T_h)

  ## Reweighting shock: a price/interest impulse, as in Phase-0/1 (kept at
  ## the Phase-1 default so the reweighting side is numerically identical to
  ## the earlier waves' construction -- only the macro side is new here).
  rw_shock <- list(r = 0.01 * 0.8^(seq_len(T_h) - 1L))
  sv <- .hank_phase0_survey(ag, inc, betas, omega, eis = 1, r = mks_truth$r, w = mks_truth$w,
                             T_h = T_h, shock = rw_shock, N = N_survey)
  W_rw <- hank_reweight_metric(sv$D0, sv$D1, N = N_survey)$W

  argmin_idx <- function(M) {
    idx <- which(M == min(M), arr.ind = TRUE)[1L, ]
    list(centre = centre_grid[idx[1L]], spread = spread_grid[idx[2L]])
  }

  n_c <- length(centre_grid); n_s <- length(spread_grid)
  per_T <- vector("list", length(T_data_grid))
  names(per_T) <- paste0("T_data_", T_data_grid)

  for (Ti in seq_along(T_data_grid)) {
    T_data <- T_data_grid[Ti]

    ## ---- (a) simulate a macro series from the TRUTH model ---------------
    Y_sim <- hank_mixture_simulate(model_truth, shock_specs, observables,
                                    T_data = T_data, me_variance = 0, seed = NULL)
    me_var_col <- (me_frac * apply(Y_sim, 2, stats::sd))^2
    me_var_T   <- max(me_var_col)             # shared-scalar convention (see Details)
    Y_obs <- Y_sim + matrix(stats::rnorm(T_data * length(observables), 0,
                                          sqrt(me_var_T)),
                             T_data, length(observables))
    Y_obs <- scale(Y_obs, center = TRUE, scale = FALSE)
    attr(Y_obs, "scaled:center") <- NULL
    Y_obs <- matrix(Y_obs, T_data, length(observables), dimnames = list(NULL, observables))

    ## ---- (c) grid of candidate (centre, spread) mixtures -----------------
    rho_KF_mat  <- matrix(NA_real_, n_c, n_s)
    rho_rw_mat  <- matrix(NA_real_, n_c, n_s)
    joint_mat   <- matrix(NA_real_, n_c, n_s)

    for (ci in seq_len(n_c)) for (si in seq_len(n_s)) {
      cc <- centre_grid[ci]; ss <- spread_grid[si]
      betas_cand <- c(cc - ss, cc + ss)

      ll <- hank_mixture_kf_loglik(betas_cand, omega, Y_obs, obs_vars = observables,
                                    shock_specs = shock_specs, a_grid = ag, Pi = inc$Pi,
                                    e = inc$e, eis = 1, alpha = alpha, delta = delta, Z = Z,
                                    T_h = T_h, me_variance = me_var_T)
      rho_KF_mat[ci, si] <- -ll                # negate: loglik (higher=better) -> loss

      blocks_cand <- hank_mixture_blocks(ag, inc$Pi, inc$e, betas = betas_cand,
                                          eis = 1, r = mks_truth$r, w = mks_truth$w)
      JD_cand <- hank_mixture_dist_jacobian(blocks_cand, omega, T_h, inputs = names(rw_shock))
      loss_rw <- hank_reweighting_loss(sv$dD_hat, JD_cand, rw_shock, W = W_rw)
      rho_rw_mat[ci, si] <- loss_rw$rho

      joint_mat[ci, si] <- rho_KF_mat[ci, si] + lambda * rho_rw_mat[ci, si]
    }

    per_T[[Ti]] <- list(T_data = T_data,
                         rho_KF = rho_KF_mat, rho_rw = rho_rw_mat, joint = joint_mat,
                         argmin_KF    = argmin_idx(rho_KF_mat),
                         argmin_rw    = argmin_idx(rho_rw_mat),
                         argmin_joint = argmin_idx(joint_mat))
  }

  list(T_data_grid = T_data_grid, centre_grid = centre_grid, spread_grid = spread_grid,
       truth = list(centre = centre_star, spread = spread_star),
       per_T = per_T)
}


