#' Joint macro-KF + LEVEL + single-snapshot-reweighting log-posterior for a
#' beta-mixture
#'
#' @section Recommended posterior route (read before hand-rolling a sampler):
#' The \code{(centre, spread)} posterior is a TILTED, strongly ANISOTROPIC
#' ridge -- the coordinates are highly correlated and the per-channel Fisher
#' informations differ by orders of magnitude (LEVEL identifies \code{spread}
#' with Fisher \eqn{\sim 10^7}; macro identifies \code{centre} with Fisher
#' \eqn{\sim 10^4}; the price-shock RESPONSE channel is nearly flat). A
#' DIAGONAL-metric random-walk Metropolis fails on this geometry. Use one of
#' the two supported routes instead: (i) the exact evaluation GRID via
#' \code{\link{hank_mixture_emulator}} + \code{\link{hank_mixture_sbc}}
#' (\code{sampler = "grid"} is the only implemented SBC sampler, for exactly
#' this reason), or (ii) a CURVATURE-AWARE proposal from
#' \code{\link{hank_mixture_laplace}} (mode + Laplace covariance of THIS
#' log-posterior) to seed / scale a tilted-ridge or independence sampler.
#'
#' The het-preferences-in-HANK estimator's core object: the JOINT
#' log-posterior of a 2-type discount-factor mixture over up to THREE
#' composable, all-optional observable channels, each evaluated over ONE
#' shared mixture general-equilibrium steady state
#' (\code{\link{hank_mixture_ks_steady}}) at the candidate calibration:
#' \describe{
#'   \item{macro}{the structural macro Kalman-filter log-likelihood
#'     (\code{\link{hank_mixture_kf_loglik}}) on an observed aggregate time
#'     series \code{data}; active iff \code{data} is supplied.}
#'   \item{level}{the grid-invariant functional LEVEL log-likelihood
#'     (\code{\link{hank_reweight_functional_loss}} against
#'     \code{\link{hank_reweight_level_metric}}) of a SINGLE stationary
#'     wealth cross-section survey \code{m_lev_hat} against the candidate's
#'     stationary distribution \code{D0}; active iff \code{m_lev_hat} is
#'     supplied.}
#'   \item{response}{the grid-invariant functional REWEIGHTING log-likelihood
#'     (\code{\link{hank_reweight_functional_loss}}) of a SINGLE post-shock
#'     cross-section snapshot (\code{\link{hank_dist_response_snapshot}})
#'     against an observed net reweighting \code{dD_hat}; active iff both
#'     \code{dD_hat} and \code{metric} are supplied.}
#' }
#' At least one channel must be active.
#'
#' \strong{The LEVEL channel is the corrected identifier of the mixture
#' spread}: the discount-factor SPREAD is identified by the stationary
#' wealth-distribution LEVEL (how differently the two types' stationary
#' asset holdings are distributed), not by the price-shock reweighting
#' RESPONSE (which differences out most of that level signal at a realistic
#' survey size and shock, and is nearly inert about the spread -- see the
#' file section comment above and the LEVEL cross-section observable's
#' certification log). The macro block remains informative about the
#' \code{centre} (the average discount factor governs the aggregate
#' capital/consumption response to a TFP shock). The response channel is
#' kept for completeness/backward compatibility (the original Wave-3
#' construction) but is not, on its own, an effective spread identifier.
#'
#' The return value keeps \code{loglik} (the data-driven log-likelihood
#' alone) separate from \code{logpost} (which additionally folds in
#' \code{log_prior}): this avoids the "\code{$loglik} footgun" where a
#' sampler mistakenly reads a prior-contaminated scalar as a pure
#' likelihood (e.g. for a likelihood-ratio diagnostic, an SBC rank statistic,
#' or a nested annealing/tempering scheme that must apply its own
#' temperature to the likelihood only) -- a caller wanting a Bayesian
#' posterior for MCMC should use \code{logpost}; a caller building its own
#' prior/temperature externally, or auditing the likelihood in isolation,
#' should use \code{loglik} (further decomposed into \code{loglik_macro},
#' \code{loglik_rw} and \code{loglik_level} for diagnosing which block is
#' driving the result).
#'
#' @param theta A list with \code{$centre} (the mixture's mean discount
#'   factor) and \code{$spread} (half the gap between the two types' discount
#'   factors, so \code{betas = c(centre - spread, centre + spread)}); may
#'   optionally include \code{$omega} (length-2 mixture weights), in which
#'   case it OVERRIDES \code{config$omega} for this evaluation (e.g. when a
#'   sampler is also exploring the mixture weight); if \code{theta$omega} is
#'   \code{NULL}, \code{config$omega} is used.
#' @param data \code{T_data x length(config$observables)} matrix of demeaned
#'   macro observations, as expected by \code{\link{hank_mixture_kf_loglik}}
#'   / \code{\link{hank_kalman_loglik}}; \code{NULL} (default) disables the
#'   macro channel.
#' @param dD_hat Observed net reweighting, a length-\code{n_cell} numeric
#'   vector (e.g. \code{Dhat1 - Dhat0} of two independently-sampled survey
#'   cross-sections, pre- and post-shock; see
#'   \code{\link{hank_reweight_functional_loss}}); \code{NULL} (default)
#'   disables the response channel (together with \code{metric}).
#' @param metric A metric object from
#'   \code{\link{hank_reweight_functional_metric}} (built once from a
#'   reference \code{(D0, D1)} pair and reused across candidate mixtures);
#'   \code{NULL} (default) disables the response channel (together with
#'   \code{dD_hat}).
#' @param config A list of items shared across every evaluation of this
#'   log-posterior (typically fixed for a whole sampler run), with:
#'   \describe{
#'     \item{\code{a_grid, Pi, e}}{Household asset grid, income transition,
#'       income levels, shared across mixture types (see
#'       \code{\link{hank_mixture_ks_steady}}).}
#'     \item{\code{eis}}{Elasticity of intertemporal substitution, shared
#'       across types.}
#'     \item{\code{alpha, delta}}{Capital share and depreciation.}
#'     \item{\code{Z}}{Steady-state TFP.}
#'     \item{\code{T_h}}{Integer GE/impulse-response horizon (shared by the
#'       macro state space and the reweighting Jacobians); only required when
#'       the macro or response channel is active.}
#'     \item{\code{observables}}{Character vector of observable names for the
#'       macro block (see \code{\link{hank_mixture_kf_loglik}}); only required
#'       when the macro channel is active.}
#'     \item{\code{shock_specs}}{Named list, one entry per exogenous macro
#'       shock, each \code{list(rho, sigma)} (see
#'       \code{\link{hank_state_space}}); only required when the macro
#'       channel is active.}
#'     \item{\code{me_var}}{Macro measurement-error variance (see
#'       \code{\link{hank_kalman_loglik}}); only required when the macro
#'       channel is active.}
#'     \item{\code{rw_shock}}{Named list, one length-\code{T_h} shock path per
#'       reweighting input (see \code{\link{hank_dist_response_snapshot}}'s
#'       \code{dZ}); only required when the response channel is active.}
#'     \item{\code{t_star}}{Integer output date in \code{1..T_h} at which the
#'       single reweighting snapshot is taken (see
#'       \code{\link{hank_dist_response_snapshot}}); only required when the
#'       response channel is active.}
#'     \item{\code{rw_scale}}{Scalar multiplier applied to the snapshot
#'       response before scoring against \code{dD_hat} (the size of the
#'       reweighting-side shock); only required when the response channel is
#'       active.}
#'     \item{\code{omega}}{Default length-2 mixture weights, used whenever
#'       \code{theta$omega} is \code{NULL}.}
#'     \item{\code{q}}{Optional truncation horizon passed to
#'       \code{\link{hank_state_space}} (default \code{T_h} if absent/\code{NULL});
#'       only relevant when the macro channel is active.}
#'   }
#' @param m_lev_hat Observed LEVEL survey: a length-\code{ncol(level_metric$B)}
#'   numeric vector, the projection \code{t(B) Dhat} of a SINGLE size-\code{N}
#'   multinomial cross-section \code{Dhat} drawn from a stationary wealth
#'   distribution (see \code{\link{hank_reweight_level_metric}}); \code{NULL}
#'   (default) disables the level channel.
#' @param level_metric A metric object from
#'   \code{\link{hank_reweight_level_metric}} (built once from a reference
#'   stationary distribution and reused across candidate mixtures); required
#'   whenever \code{m_lev_hat} is supplied (an error is raised otherwise).
#' @param log_prior Optional function of \code{theta} returning a single
#'   scalar log-prior density; if \code{NULL} (the default), the log-prior is
#'   taken to be \code{0} (i.e. \code{logpost == loglik}).
#'
#' @return A list with:
#'   \item{logpost}{\code{loglik + logprior} (the quantity an MCMC sampler
#'     should target).}
#'   \item{loglik}{\code{loglik_macro + loglik_rw + loglik_level}, the data
#'     log-likelihood WITHOUT the prior (see Details for why this is kept
#'     separate); inactive channels contribute \code{0}.}
#'   \item{loglik_macro}{The structural Kalman-filter macro log-likelihood
#'     alone (\code{\link{hank_mixture_kf_loglik}}'s value at this
#'     \code{theta}), or \code{0} if the macro channel is inactive.}
#'   \item{loglik_rw}{The reweighting (response) log-likelihood alone,
#'     \code{-0.5 * hank_reweight_functional_loss(dD_hat, dD_mod, metric)$rho}
#'     at the date-\code{t_star} snapshot of this \code{theta}'s
#'     distribution-Jacobian response, or \code{0} if the response channel is
#'     inactive.}
#'   \item{loglik_level}{The LEVEL log-likelihood alone,
#'     \code{-0.5 * hank_reweight_functional_loss(m_lev_hat, D0, level_metric)$rho}
#'     at this \code{theta}'s stationary distribution \code{D0}, or \code{0}
#'     if the level channel is inactive.}
#'   \item{logprior}{\code{log_prior(theta)}, or \code{0} if \code{log_prior}
#'     is \code{NULL}.}
#' @seealso \code{\link{hank_mixture_kf_loglik}}, \code{\link{hank_reweight_functional_loss}},
#'   \code{\link{hank_reweight_level_metric}}, \code{\link{hank_dist_response_snapshot}},
#'   \code{\link{hank_mixture_dist_jacobian}}, \code{\link{hank_reweight_functional_metric}}
#' @export
hank_mixture_joint_logpost <- function(theta, data = NULL, dD_hat = NULL, metric = NULL,
                                       config, m_lev_hat = NULL, level_metric = NULL,
                                       log_prior = NULL) {
  use_macro <- !is.null(data)
  use_resp  <- !is.null(dD_hat) && !is.null(metric)
  use_level <- !is.null(m_lev_hat)
  if (use_level && is.null(level_metric))
    stop("hank_mixture_joint_logpost(): 'm_lev_hat' was supplied without 'level_metric'; ",
         "the level channel requires a hank_reweight_level_metric() object.")
  if (!use_macro && !use_resp && !use_level)
    stop("hank_mixture_joint_logpost(): no channel is active -- supply at least one of ",
         "'Y' (macro), 'm_lev_hat' (level), or 'dD_hat'+'metric' (response).")

  centre <- theta$centre; spread <- theta$spread
  omega  <- if (!is.null(theta$omega)) theta$omega else config$omega
  betas  <- c(centre - spread, centre + spread)

  ## ---- one shared mixture GE steady state (needed by macro, and to get
  ## r, w for level/response) ----
  mks <- hank_mixture_ks_steady(config$a_grid, config$Pi, config$e, betas, omega,
                                eis = config$eis, alpha = config$alpha,
                                delta = config$delta, Z = config$Z)

  ## ---- macro: truncated-MA state space + Kalman filter ----
  loglik_macro <- 0
  if (use_macro) {
    ss <- hank_state_space(hank_mixture_ks_model(mks, config$T_h),
                           config$shock_specs, config$observables, q = config$q)
    loglik_macro <- hank_kalman_loglik(data, ss, me_variance = config$me_var)
  }

  ## ---- one shared set of per-type blocks (needed by EITHER level or
  ## response -- reused for both) ----
  loglik_rw <- 0
  loglik_level <- 0
  if (use_level || use_resp) {
    b <- hank_mixture_blocks(config$a_grid, config$Pi, config$e, betas = betas,
                             eis = config$eis, r = mks$r, w = mks$w)

    ## ---- response: single post-shock cross-section snapshot reweighting ----
    if (use_resp) {
      JD <- hank_mixture_dist_jacobian(b, omega, config$T_h, inputs = "r")
      dD_mod <- config$rw_scale *
        hank_dist_response_snapshot(JD, config$rw_shock, config$t_star)
      loglik_rw <- -0.5 * hank_reweight_functional_loss(dD_hat, dD_mod, metric)$rho
    }

    ## ---- level: single stationary cross-section survey ----
    if (use_level) {
      D0 <- hank_mixture_dist(b, omega)$D
      loglik_level <- -0.5 * hank_reweight_functional_loss(m_lev_hat, D0, level_metric)$rho
    }
  }

  ## ---- prior + assemble (loglik kept separate from logpost) ----
  logprior <- if (is.null(log_prior)) 0 else log_prior(theta)
  loglik   <- loglik_macro + loglik_rw + loglik_level
  list(logpost = loglik + logprior, loglik = loglik,
       loglik_macro = loglik_macro, loglik_rw = loglik_rw, loglik_level = loglik_level,
       logprior = logprior)
}


#' Laplace (mode + curvature) proposal for the HANK-mixture joint posterior
#'
#' Finds the posterior mode of \code{\link{hank_mixture_joint_logpost}} over the
#' free scalar coordinates (\code{centre}, \code{spread}, and optionally the
#' first mixture weight \code{omega1}), computes the observed information
#' \eqn{-\nabla^2 \log p} there by a central finite difference, and returns the
#' Laplace covariance \eqn{(-\nabla^2 \log p)^{-1}} together with a Gaussian
#' proposal sampler.
#'
#' \strong{Why this exists.} The mixture posterior on \code{(centre, spread)} is
#' a strongly TILTED, ANISOTROPIC RIDGE: the two coordinates are highly
#' correlated and the channel Fisher informations differ by orders of magnitude
#' (the stationary-wealth LEVEL channel identifies the spread with Fisher
#' \eqn{\sim 10^7}, the macro channel identifies the centre with Fisher
#' \eqn{\sim 10^4}, the price-shock RESPONSE channel is nearly flat). A
#' DIAGONAL-metric random-walk Metropolis fails badly on this geometry (it
#' cannot climb the ridge and degenerates). The two routes that work are
#' (i) the exact evaluation GRID via \code{\link{hank_mixture_emulator}} +
#' \code{\link{hank_mixture_sbc}} (\code{sampler = "grid"} is the only supported
#' SBC sampler for exactly this reason), and (ii) a CURVATURE-AWARE proposal:
#' this function's Laplace covariance is the correlated metric a tilted-ridge
#' random-walk / independence proposal needs, and it is exact to \eqn{O(1/T)} at
#' the mode -- no pilot run, no importance-sampling degeneracy, no grid. Use it
#' to seed / scale a sampler or as an importance proposal; the exact grid
#' remains the gold standard for the final posterior when the ridge is
#' materially non-Gaussian.
#'
#' @param theta0 A named list giving the STARTING point and the FIXED values of
#'   any coordinate not in \code{par_names}: \code{$centre}, \code{$spread}, and
#'   (optionally) \code{$omega} (length-2 mixture weights). Same shape as the
#'   \code{theta} argument of \code{\link{hank_mixture_joint_logpost}}.
#' @param config,data,dD_hat,metric,m_lev_hat,level_metric,log_prior Passed through
#'   verbatim to \code{\link{hank_mixture_joint_logpost}} on every evaluation;
#'   supply the same channel arguments you intend to sample under (at least one
#'   of \code{data}, \code{m_lev_hat}, or \code{dD_hat}+\code{metric}).
#' @param par_names Character subset of \code{c("centre", "spread", "omega1")}
#'   giving the FREE coordinates (default \code{c("centre", "spread")}).
#'   \code{"omega1"} maps to \code{theta$omega = c(omega1, 1 - omega1)}.
#' @param method,lower,upper Passed to \code{\link[stats]{optim}} for the
#'   mode-find (default \code{"Nelder-Mead"}, unconstrained; pass box bounds
#'   with \code{method = "L-BFGS-B"} to constrain, e.g. \code{spread > 0}).
#' @param h_rel Relative central-FD step for the mode Hessian (default 2e-3;
#'   the step for coordinate \code{k} is \code{h_rel * max(abs(mode_k), 1e-4)}).
#'   This is DELIBERATELY LARGER than a textbook \code{~1e-5} Hessian step: the
#'   log-posterior is a general-equilibrium (uniroot market-clearing) solve, so
#'   it is smooth only down to the clearing tolerance, and a second difference
#'   (which divides by \code{h^2}) at a tiny step is swamped by that
#'   non-smoothness -- catastrophically in a TIGHT direction. Empirically the FD
#'   curvature converges as \code{h} grows: at \code{h_rel = 1e-4} a
#'   sharply-identified coordinate (e.g. \code{spread} under the LEVEL channel)
#'   can be over-curved by \code{~8x}; it is within a few percent of the true
#'   marginal by \code{h_rel = 2e-3}--\code{3e-3}. INCREASE \code{h_rel} if the
#'   tightest-direction \code{sd} looks under-estimated (Hessian noise-dominated);
#'   DECREASE it if a probe walks off the GE-solvable region (\code{cov = NULL}).
#' @param optim_control Extra \code{control} list merged into
#'   \code{list(fnscale = -1, reltol = 1e-10)} (the negative \code{fnscale}
#'   makes \code{optim} MAXIMISE the log-posterior).
#'
#' @return A list with \item{mode}{named numeric, the posterior mode over
#'   \code{par_names}.} \item{logpost}{log-posterior at the mode.}
#'   \item{hessian}{FD Hessian of the LOG-POSTERIOR at the mode (negative
#'     definite at a maximum).} \item{information}{\code{-hessian}, the observed
#'     information (should be positive definite).} \item{cov}{Laplace covariance
#'     \code{solve(information)}, or \code{NULL} with a warning if the
#'     information is not positive definite (mode not a strict max / a coordinate
#'     unidentified by the active channels).} \item{sd}{\code{sqrt(diag(cov))}.}
#'   \item{propose}{\code{function(n)} drawing \code{n} rows from
#'     \code{MVN(mode, cov)} (a matrix with columns \code{par_names}); errors if
#'     \code{cov} is \code{NULL}.} \item{to_theta}{\code{function(v)} mapping a
#'     named \code{par_names} vector back to the list-\code{theta} that
#'     \code{hank_mixture_joint_logpost} consumes (fixed coordinates from
#'     \code{theta0}).} \item{par_names, converged}{bookkeeping.}
#' @seealso \code{\link{hank_mixture_joint_logpost}},
#'   \code{\link{hank_mixture_emulator}}, \code{\link{hank_mixture_sbc}}
#' @export
hank_mixture_laplace <- function(theta0, config,
                                 data = NULL, dD_hat = NULL, metric = NULL,
                                 m_lev_hat = NULL, level_metric = NULL,
                                 log_prior = NULL,
                                 par_names = c("centre", "spread"),
                                 method = "Nelder-Mead",
                                 lower = -Inf, upper = Inf,
                                 h_rel = 2e-3,
                                 optim_control = list()) {

  par_names <- match.arg(par_names, c("centre", "spread", "omega1"),
                         several.ok = TRUE)
  if ("omega1" %in% par_names &&
      (is.null(theta0$omega) || length(theta0$omega) != 2L))
    stop("hank_mixture_laplace(): par_names includes 'omega1' but theta0$omega ",
         "is not a length-2 weight vector.")

  ## flat par vector -> list-theta (fixed coords come from theta0)
  to_theta <- function(v) {
    th <- theta0
    if ("centre" %in% names(v)) th$centre <- v[["centre"]]
    if ("spread" %in% names(v)) th$spread <- v[["spread"]]
    if ("omega1" %in% names(v)) th$omega  <- c(v[["omega1"]], 1 - v[["omega1"]])
    th
  }

  ## objective: the log-posterior as a function of the flat par vector.
  ## Infeasible / non-finite draws are penalised so the optimiser and the FD
  ## stencil stay inside the well-defined region.
  ## Objective evaluations during the mode-search and FD stencil routinely probe
  ## points where a type's household EGM / market-clearing solve does not
  ## converge (expected: the optimiser explores, the FD stencil steps out); such
  ## a probe returns the penalty and the search moves on, so its GE-solve
  ## warnings are noise here and are suppressed. The returned mode/cov are
  ## validated separately (PD information + `converged`).
  neg_inf_pen <- -1e18
  f <- function(v) {
    vv <- setNames(as.numeric(v), par_names)
    r <- tryCatch(
      suppressWarnings(
        hank_mixture_joint_logpost(to_theta(vv), data = data, dD_hat = dD_hat,
                                   metric = metric, config = config,
                                   m_lev_hat = m_lev_hat,
                                   level_metric = level_metric,
                                   log_prior = log_prior)),
      error = function(e) NULL)
    if (is.null(r) || !is.finite(r$logpost)) return(neg_inf_pen)
    r$logpost
  }

  v0 <- vapply(par_names, function(nm)
    if (nm == "omega1") theta0$omega[1L] else theta0[[nm]], numeric(1))
  names(v0) <- par_names

  ctrl <- utils::modifyList(list(fnscale = -1, reltol = 1e-10), optim_control)
  opt <- stats::optim(v0, f, method = method, lower = lower, upper = upper,
                      control = ctrl)
  mode <- setNames(opt$par, par_names)

  ## central-FD Hessian of the log-posterior at the mode (3-point diagonal,
  ## 4-corner mixed) -- small (<= 3 coords), so O(p^2) forward evals is cheap.
  p  <- length(par_names)
  hs <- h_rel * pmax(abs(mode), 1e-4)
  f0 <- f(mode)
  H  <- matrix(0, p, p, dimnames = list(par_names, par_names))
  fe <- function(delta) f(mode + delta)
  for (i in seq_len(p)) {
    ei <- numeric(p); ei[i] <- hs[i]
    H[i, i] <- (fe(ei) - 2 * f0 + fe(-ei)) / (hs[i]^2)
  }
  if (p > 1L) for (i in seq_len(p - 1L)) for (j in (i + 1L):p) {
    ei <- numeric(p); ei[i] <- hs[i]
    ej <- numeric(p); ej[j] <- hs[j]
    hij <- (fe(ei + ej) - fe(ei - ej) - fe(-ei + ej) + fe(-ei - ej)) /
      (4 * hs[i] * hs[j])
    H[i, j] <- hij; H[j, i] <- hij
  }

  information <- -H
  cov <- tryCatch({
    ch <- chol(information)          # errors unless PD
    chol2inv(ch)
  }, error = function(e) NULL)
  if (is.null(cov)) {
    warning("hank_mixture_laplace(): the observed information at the mode is ",
            "not positive definite (mode not a strict maximum, or a coordinate ",
            "is unidentified by the active channels). Returning cov = NULL; add ",
            "an identifying channel (e.g. the LEVEL survey for 'spread') or fix ",
            "that coordinate.", call. = FALSE)
    sd_out <- setNames(rep(NA_real_, p), par_names)
    propose <- function(n) stop("hank_mixture_laplace: cov is NULL; no proposal.")
  } else {
    dimnames(cov) <- list(par_names, par_names)
    sd_out <- setNames(sqrt(diag(cov)), par_names)
    L <- chol(cov)                   # cov = t(L) %*% L
    propose <- function(n) {
      Z <- matrix(stats::rnorm(n * p), n, p)
      out <- Z %*% L + matrix(mode, n, p, byrow = TRUE)
      colnames(out) <- par_names
      out
    }
  }

  list(mode = mode, logpost = f0, hessian = H, information = information,
       cov = cov, sd = sd_out, propose = propose, to_theta = to_theta,
       par_names = par_names, converged = (opt$convergence == 0L))
}
