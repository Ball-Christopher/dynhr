## R/hank-mixture-estimation.R
## --------------------------------------------------------------------------
## Phase-1 Wave-2 (part 2): the STRUCTURAL JOINT estimator for the het-
## preferences-in-HANK research line (brief-17).
##
## Phase-1 Wave-1 (R/hank-reweighting.R, hank_phase1_joint_gate) showed that a
## JOINT objective -- a noisy MACRO aggregate path plus the net cross-section
## REWEIGHTING loss -- can recover both the beta-mixture's centre and spread,
## where either loss alone is degenerate along one grid direction. Its macro
## side used a simple noisy-IRF-path proxy (hank_macro_loss / AC_hat_macro),
## which turned out to be MORE informative about the centre than a real
## macroeconometrician would have: an econometrician does not observe the
## clean impulse-response path AC_star + iid noise at every t of a KNOWN
## shock date/size, they observe a finite TIME SERIES generated by repeated,
## a priori unknown shock realizations, filtered through a Kalman filter that
## must integrate out the shock path itself.
##
## This file replaces that macro proxy with the REALISTIC one: a Kalman
## filter (R/hank-kalman.R's hank_state_space / hank_kalman_loglik) evaluated
## on a synthetic macro TIME SERIES of finite length T_data, simulated from
## the mixture model's own truncated-MA state space. Because a finite series
## carries only finite information about the underlying preference mixture,
## the beta-mixture (centre, spread) is here GENUINELY weakly identified from
## macro data alone -- exactly the setting in which the reweighting side's
## contribution (Phase-0/Phase-1 Wave-1) is expected to show its value, in
## contrast to Wave-1's overly-informative clean-IRF macro proxy.
##
## PIPELINE (per function):
##   hank_mixture_kf_loglik():  eta = (betas, omega) -> mixture steady state
##     (hank_mixture_ks_steady) -> mixture GE model (hank_mixture_ks_model)
##     -> truncated-MA state space (hank_state_space) -> Kalman loglik
##     (hank_kalman_loglik). This is the "structural" macro likelihood: unlike
##     hank_macro_loss's noiseless IRF-moment proxy, it is a genuine Gaussian
##     likelihood over a stochastic time series, integrating over the shock's
##     own realization via the state-space recursion.
##   hank_mixture_simulate():   draws that same synthetic time series from a
##     given mixture model's MA representation (mirrors
##     hank_simulate_aggregate() in R/hank-estimation.R, generalized to the
##     multi-observable / hank_state_space() convention).
##   hank_phase2_recovery():    the (centre, spread) grid-search driver,
##     combining hank_mixture_kf_loglik (macro-alone), hank_reweighting_loss
##     (reweight-alone, reusing Phase-0/1 machinery) and their sum (joint),
##     across a T_data_grid to show how the macro side sharpens as the series
##     lengthens while the reweighting side remains available regardless of
##     T_data (it comes from a snapshot survey pair, not the time series).
## --------------------------------------------------------------------------


#' Structural (Kalman-filter) macro log-likelihood of a beta-mixture HANK model
#'
#' The eta-dependent structural macro log-likelihood at a candidate
#' beta-mixture calibration \code{eta = (betas, omega)}: solves the mixture
#' steady state and GE model at \code{eta}, converts it to a truncated-MA
#' state space, and evaluates dynhr's Gaussian Kalman filter on the observed
#' aggregate time series \code{data}. Unlike \code{\link{hank_macro_loss}}'s
#' noiseless-IRF-moment proxy (Phase-1 Wave-1), this is a genuine Gaussian
#' likelihood over a STOCHASTIC time series of finite length, integrating
#' over the shock's own realization via the state-space recursion -- the
#' "realistic" macro likelihood this Phase-2 wave is built around.
#'
#' \strong{Stochastic singularity}: with \code{length(observables) > 1} but a
#' single exogenous shock (\code{n_obs = 2 > n_shock = 1} for the default
#' \code{observables = c("C","K")}), the model-implied observation covariance
#' is rank-\code{n_shock} and thus singular whenever \code{n_obs > n_shock}.
#' \code{me_variance > 0} is therefore \strong{required} in that regime (as in
#' \code{\link{hank_kalman_loglik}}'s own singularity note) -- it is not
#' optional measurement-error realism here, it is what keeps the observation
#' covariance non-singular so the Gaussian density is well-defined.
#'
#' @param betas Numeric length-K vector of discount factors, one per mixture
#'   type (see \code{\link{hank_mixture_ks_steady}}).
#' @param omega Numeric length-K mixture weights, non-negative, summing to 1.
#' @param data \code{T_data x length(observables)} matrix of demeaned
#'   observations, columns in the order of \code{obs_vars} (as expected by
#'   \code{\link{hank_kalman_loglik}}).
#' @param obs_vars Character vector of observable names produced by the
#'   mixture model (default \code{c("C","K")}).
#' @param shock_specs Named list, one entry per exogenous shock, each
#'   \code{list(rho = <AR(1) persistence>, sigma = <innovation std>)} (see
#'   \code{\link{hank_state_space}}). The Krusell-Smith-style mixture model
#'   built by \code{\link{hank_mixture_ks_model}} has a single exogenous
#'   shock \code{"Z"}, so \code{shock_specs} is typically
#'   \code{list(Z = list(rho = ..., sigma = ...))}.
#' @param a_grid,Pi,e Household asset grid, income transition, income levels
#'   (shared by every mixture type; see \code{\link{hank_mixture_ks_steady}}).
#' @param eis Elasticity of intertemporal substitution, shared across types
#'   (default 1).
#' @param alpha,delta Capital share and depreciation.
#' @param Z Steady-state TFP (default 1).
#' @param T_h Integer GE/impulse-response horizon (see
#'   \code{\link{hank_mixture_ks_model}}, \code{\link{hank_state_space}}).
#' @param q Optional truncation horizon passed to \code{\link{hank_state_space}}
#'   (default \code{T_h}, i.e. no truncation beyond the GE horizon).
#' @param me_variance Measurement-error variance added to every observable's
#'   diagonal in the Kalman filter (see \code{\link{hank_kalman_loglik}}).
#'   \strong{Required to be strictly positive} whenever
#'   \code{length(observables) > 1} for a single-shock model (see Details).
#'
#' @return The scalar Gaussian log-likelihood (higher is better).
#' @seealso \code{\link{hank_mixture_ks_steady}}, \code{\link{hank_mixture_ks_model}},
#'   \code{\link{hank_state_space}}, \code{\link{hank_kalman_loglik}},
#'   \code{\link{hank_mixture_simulate}}, \code{\link{hank_phase2_recovery}}
#' @export
hank_mixture_kf_loglik <- function(betas, omega, data, obs_vars = c("C", "K"),
                                    shock_specs, a_grid, Pi, e, eis = 1,
                                    alpha, delta, Z = 1, T_h, q = NULL,
                                    me_variance) {
  if (length(obs_vars) > length(shock_specs) &&
      (missing(me_variance) || !is.numeric(me_variance) || length(me_variance) != 1L ||
       !is.finite(me_variance) || me_variance <= 0))
    stop("hank_mixture_kf_loglik(): n_obs = ", length(obs_vars),
         " > n_shock = ", length(shock_specs),
         " is stochastically singular; 'me_variance' must be a single strictly ",
         "positive number to keep the observation covariance non-singular.")

  mks   <- hank_mixture_ks_steady(a_grid, Pi, e, betas, omega, eis = eis,
                                   alpha = alpha, delta = delta, Z = Z)
  model <- hank_mixture_ks_model(mks, T_h)
  ss    <- hank_state_space(model, shock_specs, obs_vars, q = q)
  hank_kalman_loglik(data, ss, me_variance = me_variance)
}


#' Simulate a synthetic macro time series from a mixture model's MA state space
#'
#' Draws a synthetic aggregate time series of length \code{T_data} from a
#' \code{\link{hank_model}}'s truncated-MA state space
#' (\code{\link{hank_state_space}}), for use as the "observed" macro data fed
#' to \code{\link{hank_mixture_kf_loglik}} / \code{\link{hank_kalman_loglik}}.
#'
#' Simulates directly off the MA representation (the same construction as
#' \code{\link{hank_simulate_aggregate}} in R/hank-estimation.R, generalized
#' to \code{\link{hank_state_space}}'s multi-shock / multi-observable
#' convention): for each exogenous shock, innovations
#' \eqn{\epsilon_t \sim N(0, \sigma^2)} are drawn independently for
#' \code{t = 1, ..., T_data}, and
#' \deqn{y_{o,t} = \Sigma_{s=0}^{q-1} \Theta_{shock}[s+1, o]\, \epsilon_{t-s} + N(0, me\_var),}
#' treating \eqn{\epsilon_{t-s} = 0} for \code{t - s < 1} (the process starts
#' from rest -- no pre-sample shock history), matching this exactly is what
#' keeps the simulated data on the SAME law that
#' \code{\link{hank_kalman_loglik}} evaluates (avoids any timing mismatch
#' between simulation and likelihood).
#'
#' The returned series is \strong{demeaned} (its own column means are
#' subtracted), because \code{\link{hank_kalman_loglik}} (via
#' \code{\link{hank_state_space}}'s zero-mean state-space form) expects
#' demeaned observations. Since the underlying process is already a
#' zero-mean deviation-from-steady-state law, this demeaning only removes
#' finite-sample Monte Carlo noise in the sample mean -- it does not change
#' the population data-generating process.
#'
#' @param model A \code{\link{hank_model}} (e.g. \code{\link{hank_mixture_ks_model}}'s
#'   output).
#' @param shock_specs Named list, one entry per \code{model$exogenous} shock
#'   (see \code{\link{hank_state_space}}).
#' @param obs_vars Character vector of observable names (default
#'   \code{c("C","K")}).
#' @param T_data Integer: length of the simulated series.
#' @param me_variance Measurement-error variance added to every observable
#'   (independently at every date); use \code{0} for a noiseless simulation.
#' @param seed Optional RNG seed (via \code{set.seed()}) for reproducibility;
#'   if \code{NULL}, the caller's current RNG stream is used unmodified.
#' @param q Optional truncation horizon passed to \code{\link{hank_state_space}}
#'   (default \code{model$T_h}).
#'
#' @return A \code{T_data x length(observables)} numeric matrix (columns named
#'   by \code{obs_vars}), demeaned (see Details), finite, and reproducible
#'   given the same \code{seed}.
#' @seealso \code{\link{hank_state_space}}, \code{\link{hank_mixture_kf_loglik}},
#'   \code{\link{hank_simulate_aggregate}}
#' @export
hank_mixture_simulate <- function(model, shock_specs, obs_vars = c("C", "K"),
                                   T_data, me_variance, seed = NULL, q = NULL) {
  if (!is.null(seed)) set.seed(seed)
  ss <- hank_state_space(model, shock_specs, obs_vars, q = q)
  n_obs   <- length(obs_vars)
  exo     <- ss$shock_names
  T_h_reg <- nrow(ss$Theta_list[[1L]])          # q (rows of each Theta block)

  Y <- matrix(0, T_data, n_obs)
  for (z in exo) {
    sigma_z <- shock_specs[[z]]$sigma
    eps <- stats::rnorm(T_data, 0, sigma_z)
    Theta <- ss$Theta_list[[z]]                 # T_h x n_obs (see hank_state_space)
    for (t in seq_len(T_data)) {
      s <- 0:min(t - 1L, T_h_reg - 1L)          # Theta_s eps_{t-s}, eps_{<1} = 0
      Y[t, ] <- Y[t, ] + colSums(Theta[s + 1L, , drop = FALSE] * eps[t - s])
    }
  }
  if (me_variance > 0)
    Y <- Y + matrix(stats::rnorm(T_data * n_obs, 0, sqrt(me_variance)), T_data, n_obs)

  Y <- scale(Y, center = TRUE, scale = FALSE)   # demean (see Details)
  attr(Y, "scaled:center") <- NULL
  matrix(Y, T_data, n_obs, dimnames = list(NULL, obs_vars))
}


