#' Print a Krusell-Smith aggregate-risk solution
#' @param x A \code{hank_ks_agg_risk} object.
#' @param ... Unused.
#' @return \code{x}, invisibly.
#' @export
print.hank_ks_agg_risk <- function(x, ...) {
  cat("=== hank_ks_agg_risk ===\n")
  cat(sprintf("Grids            : n_e = %d, n_a = %d, n_k = %d, n_z = %d\n",
              x$dims[["n_e"]], x$dims[["n_a"]], x$dims[["n_k"]],
              x$dims[["n_z"]]))
  cat(sprintf("Fixed point      : %s in %d outer iterations (gap %.2e)\n",
              if (isTRUE(x$converged)) "converged" else "NOT converged",
              x$iterations, x$rule_gap))
  cat(sprintf("Forecast rule R2 : %s\n",
              paste(sprintf("%.6f", x$rule$R2), collapse = "  ")))
  cat(sprintf("den Haan error   : max %.4f%%, mean %.4f%%\n",
              x$den_haan$max_pct, x$den_haan$mean_pct))
  cat(sprintf("Aggregate K      : mean %.6f, sd %.6f (deterministic ss %.6f)\n",
              x$K_mean, x$K_sd, x$K_ss))
  cat(sprintf("Elapsed          : %.2f s\n", x$elapsed))
  invisible(x)
}


#' Simulate aggregate paths from a Krusell-Smith aggregate-risk solution
#'
#' Runs the non-stochastic histogram simulation forward under a supplied or
#' drawn aggregate-shock path, returning the aggregate series the solution
#' implies.
#'
#' @param object A \code{hank_ks_agg_risk} object from
#'   \code{\link{hank_ks_aggregate_risk}}.
#' @param nsim Integer: number of independent simulated paths.
#' @param seed Integer or \code{NULL}: seed for the drawn aggregate paths (and
#'   restored on exit, per the \code{stats::simulate} contract).
#' @param T_sim Integer: length of each simulated path.
#' @param z_path Optional integer vector of aggregate-state indices to use
#'   instead of drawing one. When supplied, \code{nsim} must be 1 and
#'   \code{T_sim} is taken from its length.
#' @param D0 Optional initial cross-sectional distribution (length
#'   \code{n_e*n_a}, distribution order). Defaults to the solution's ergodic
#'   MEAN distribution, so a path starts from the stochastic steady state
#'   rather than from the deterministic one.
#' @param K0 Optional aggregate capital entering the first period; defaults to
#'   the ergodic mean of \code{K}.
#' @param burn_in Integer: leading periods dropped from the returned paths
#'   (0 by default -- the default \code{D0} is already ergodic).
#' @param ... Unused.
#'
#' @return A data frame (\code{nsim = 1}) or a list of data frames, with
#'   columns \code{t}, \code{Z}, \code{z_index}, \code{K} (capital ENTERING
#'   the period), \code{K_next}, \code{r}, \code{w}, \code{C}, \code{Y}.
#' @seealso \code{\link{hank_ks_aggregate_risk}}, \code{\link{hank_ks_risk_irf}}
#' @export
simulate.hank_ks_agg_risk <- function(object, nsim = 1, seed = NULL,
                                      T_sim = 200L, z_path = NULL,
                                      D0 = NULL, K0 = NULL, burn_in = 0L,
                                      ...) {
  nsim <- as.integer(nsim)
  if (nsim < 1L) stop("simulate.hank_ks_agg_risk(): 'nsim' must be >= 1.")
  if (!is.null(z_path) && nsim != 1L)
    stop("simulate.hank_ks_agg_risk(): 'z_path' fixes the aggregate path, so ",
         "'nsim' must be 1 (repeating the same path nsim times would return ",
         "nsim identical draws).")
  if (!is.null(seed)) {
    if (!exists(".Random.seed", envir = globalenv(), inherits = FALSE))
      stats::runif(1)
    old_seed <- get(".Random.seed", envir = globalenv(), inherits = FALSE)
    on.exit(assign(".Random.seed", old_seed, envir = globalenv()), add = TRUE)
    set.seed(as.integer(seed))
  }
  ks <- object$ks; blk <- ks$block
  n_z <- object$dims[["n_z"]]
  if (is.null(D0)) D0 <- object$ergodic$D_mean
  if (is.null(K0)) K0 <- object$ergodic$K_mean
  D0 <- as.numeric(D0)
  if (length(D0) != object$dims[["n_e"]] * object$dims[["n_a"]])
    stop("simulate.hank_ks_agg_risk(): 'D0' must have n_e*n_a = ",
         object$dims[["n_e"]] * object$dims[["n_a"]], " entries.")
  sol <- list(a_pol = object$policy$a_pol, c_pol = object$policy$c_pol)
  z0 <- if (n_z == 1L) 1L else as.integer(ceiling(n_z / 2))
  out <- vector("list", nsim)
  for (s in seq_len(nsim)) {
    zp <- if (is.null(z_path)) .hank_agg_draw_z(object$Pi_Z, as.integer(T_sim), z0)
          else as.integer(z_path)
    sp <- .hank_agg_simulate_path(sol, blk$a_grid, blk$Pi, blk$e,
                                  ks$alpha, ks$delta, object$Z_grid,
                                  object$K_grid, zp, D0, K0)
    Tn <- length(zp)
    idx <- seq.int(as.integer(burn_in) + 1L, Tn)
    out[[s]] <- data.frame(
      t = idx, z_index = zp[idx], Z = object$Z_grid[zp[idx]],
      K = sp$K[idx], K_next = sp$K[idx + 1L],
      r = sp$r[idx], w = sp$w[idx], C = sp$C[idx], Y = sp$Y[idx])
  }
  if (nsim == 1L) out[[1L]] else out
}


# =============================================================================
# Public: generalized impulse response (Koop-Pesaran-Potter)
# =============================================================================

#' Generalized impulse response of the aggregate-risk Krusell-Smith model
#'
#' Koop, Pesaran and Potter (1996) GIRF: the average difference between the
#' economy's path WITH a date-1 aggregate innovation and the path WITHOUT it,
#' both started from the ERGODIC distribution and averaged over future
#' aggregate-shock paths.
#'
#' Both replications start from ERGODIC INITIAL CONDITIONS: each draw begins
#' at a post-burn-in \eqn{(D_t, K_t)} pair of the solve's own simulation
#' (sampled without replacement where possible), so the integration over
#' initial states is over the model's ergodic set and not over an arbitrary
#' reference point. The two branches of a draw share that initial condition,
#' and share one uniform sequence \eqn{u_2, \ldots, u_H} (common random
#' numbers).
#'
#' @section Continuation of the aggregate shock:
#' \describe{
#'   \item{\code{"chain"} (default)}{The Koop-Pesaran-Potter object. After
#'     date 1 each branch follows ITS OWN conditional chain, the shared
#'     \eqn{u_h} being applied to each branch's own conditional CDF (the
#'     Rosenblatt coupling), so the innovation genuinely persists at the
#'     chain's own rate and the two branches couple when their draws
#'     coincide. Because Rouwenhorst reproduces the AR(1) conditional mean
#'     exactly, the date-\eqn{1+j} MEAN of \eqn{\log Z} differs between the
#'     branches by exactly \eqn{\rho^j \Delta} with
#'     \eqn{\Delta = \log Z_{z_{shock}} - \log Z_{z_{ref}}}, so the scaled
#'     response is comparable with \code{\link{hank_ks_linear_irf}} at
#'     \code{dZ = Z * rho^(h-1)}. Its Monte-Carlo error does NOT shrink with
#'     the shock size: while the branches are uncoupled their realized
#'     \eqn{\log Z} differ by one whole grid step, i.e. by \eqn{\Delta}
#'     itself, so the SCALED difference carries O(1) sampling noise and needs
#'     large \code{n_draws}. \code{mcse} reports it.}
#'   \item{\code{"common"}}{The shocked branch inherits the BASELINE's
#'     realized aggregate-state path from date 2 on, so the realized log-TFP
#'     difference is exactly \eqn{(\Delta, 0, 0, \ldots)} on EVERY draw.
#'     This is the response to a one-off date-1 innovation that is not
#'     followed by further TFP differences -- the nonlinear analogue of the
#'     usual "shock at date 1, zero innovations after" impulse response --
#'     and its linear counterpart is \code{hank_ks_linear_irf(ks, c(Z, 0,
#'     ..., 0))}. Households still hold the aggregate-risk policy functions,
#'     so this is a different EXPERIMENT, not a different model. Because the
#'     TFP difference is deterministic, the only remaining sampling variation
#'     is the second-order effect of the common path on the branch gap, which
#'     vanishes with the shock size: this is the low-variance object the
#'     certainty-equivalence oracle uses, and it needs only tens of draws
#'     where \code{"chain"} needs tens of thousands.}
#' }
#'
#' @param obj A \code{hank_ks_agg_risk} object.
#' @param horizon Integer: response horizon.
#' @param n_draws Integer: number of Monte-Carlo replications (initial
#'   conditions x future shock paths).
#' @param z_shock,z_ref Integer aggregate-state indices for the date-1
#'   shocked and baseline branches. Defaults: \code{z_ref} the middle state,
#'   \code{z_shock} the one above it.
#' @param continuation Character: \code{"chain"} (default) or
#'   \code{"common"}; see the section above.
#' @param return_draws Logical: also return the per-replication response and
#'   realized log-TFP difference paths (\code{dlogK_draws},
#'   \code{dlogZ_draws}, each \code{n_draws x horizon}). These are what a
#'   PATH-MATCHED comparison with a linear model needs: pairing each
#'   replication with the linear model's response to that replication's OWN
#'   realized \code{dlogZ_draws} row cancels the aggregate-shock sampling
#'   noise, leaving only the nonlinearity. The certainty-equivalence oracle
#'   uses exactly that.
#' @param seed Integer or \code{NULL}.
#'
#' @return A list with
#'   \describe{
#'     \item{\code{dlogK}}{length-\code{horizon} GIRF of \eqn{\log K}, where
#'       entry \code{h} is the response of the capital CHOSEN at date
#'       \code{h} (i.e. entering date \code{h+1}) -- the same indexing as
#'       \code{\link{hank_ks_linear_irf}}'s \code{dK}.}
#'     \item{\code{dlogK_scaled}}{\code{dlogK / delta_logZ}.}
#'     \item{\code{dlogC}, \code{dlogY}, \code{dr}, \code{dw}}{the other
#'       aggregates, dated at the period they are observed.}
#'     \item{\code{delta_logZ}}{the date-1 log-TFP innovation.}
#'     \item{\code{mcse}}{Monte-Carlo standard error of \code{dlogK}.}
#'     \item{\code{dlogZ}}{the mean realized log-TFP difference path (for
#'       \code{"chain"} this is \eqn{\rho^{h-1}\Delta} up to sampling
#'       error; for \code{"common"} it is exactly \eqn{(\Delta, 0,
#'       \ldots)}).}
#'     \item{\code{n_draws}, \code{z_shock}, \code{z_ref},
#'       \code{continuation}}{}
#'   }
#' @seealso \code{\link{hank_ks_aggregate_risk}},
#'   \code{\link{hank_ks_linear_irf}}
#' @references Koop, G., M. H. Pesaran and S. M. Potter (1996), "Impulse
#'   response analysis in nonlinear multivariate models", J. Econometrics 74.
#' @examples
#' \donttest{
#' inc    <- hank_income_rouwenhorst(rho = 0.95, sigma = 0.5, n = 3)
#' a_grid <- hank_asset_grid(amax = 50, n = 60, amin = 0)
#' ks     <- hank_ks_steady(a_grid, inc$Pi, inc$e, beta = 0.98, eis = 1,
#'                          alpha = 0.36, delta = 0.025)
#' fit <- hank_ks_aggregate_risk(ks, hank_tfp_chain(0.9, 0.03, 3),
#'                               T_sim = 400L, burn_in = 100L, seed = 1L)
#' g <- hank_ks_risk_irf(fit, horizon = 20L, n_draws = 40L, seed = 2L)
#' g$dlogK_scaled[1:5]
#' }
#' @export
hank_ks_risk_irf <- function(obj, horizon = 40L, n_draws = 200L,
                             z_shock = NULL, z_ref = NULL,
                             continuation = c("chain", "common"),
                             return_draws = FALSE, seed = NULL) {
  continuation <- match.arg(continuation)
  if (!inherits(obj, "hank_ks_agg_risk"))
    stop("hank_ks_risk_irf(): 'obj' must be a hank_ks_aggregate_risk() ",
         "object.")
  n_z <- obj$dims[["n_z"]]
  if (n_z < 2L)
    stop("hank_ks_risk_irf(): the aggregate chain is degenerate (n_z = 1); ",
         "there is no aggregate innovation to respond to.")
  if (is.null(z_ref))   z_ref   <- as.integer(ceiling(n_z / 2))
  if (is.null(z_shock)) z_shock <- min(n_z, z_ref + 1L)
  z_ref <- as.integer(z_ref); z_shock <- as.integer(z_shock)
  if (z_ref < 1L || z_ref > n_z || z_shock < 1L || z_shock > n_z)
    stop("hank_ks_risk_irf(): 'z_ref' / 'z_shock' must index the aggregate ",
         "chain (1..", n_z, ").")
  if (z_ref == z_shock)
    stop("hank_ks_risk_irf(): 'z_shock' must differ from 'z_ref' -- an ",
         "identical pair has a zero innovation and the scaled response ",
         "would be 0/0.")
  horizon <- as.integer(horizon); n_draws <- as.integer(n_draws)
  if (horizon < 1L || n_draws < 1L)
    stop("hank_ks_risk_irf(): 'horizon' and 'n_draws' must be >= 1.")

  if (!is.null(seed)) {
    if (!exists(".Random.seed", envir = globalenv(), inherits = FALSE))
      stats::runif(1)
    old_seed <- get(".Random.seed", envir = globalenv(), inherits = FALSE)
    on.exit(assign(".Random.seed", old_seed, envir = globalenv()), add = TRUE)
    set.seed(as.integer(seed))
  }

  ks <- obj$ks; blk <- ks$block
  sol <- list(a_pol = obj$policy$a_pol, c_pol = obj$policy$c_pol)
  Dsam <- obj$ergodic$D_sample
  Ksam <- obj$ergodic$K_sample
  n_sam <- ncol(Dsam)
  start_idx <- if (n_draws <= n_sam)
    sort(sample.int(n_sam, n_draws, replace = FALSE))
  else sample.int(n_sam, n_draws, replace = TRUE)

  cdf <- t(apply(obj$Pi_Z, 1L, cumsum))
  step_z <- function(cur, u) {
    nx <- as.integer(1L + sum(cdf[cur, ] < u))
    if (nx > n_z) n_z else nx
  }

  dK <- matrix(0, n_draws, horizon)
  dZl <- matrix(0, n_draws, horizon)
  dC <- matrix(0, n_draws, horizon); dY <- matrix(0, n_draws, horizon)
  drr <- matrix(0, n_draws, horizon); dww <- matrix(0, n_draws, horizon)
  for (d in seq_len(n_draws)) {
    D0 <- Dsam[, start_idx[d]]
    K0 <- Ksam[start_idx[d]]
    u  <- stats::runif(horizon)                 # common random numbers
    zb <- integer(horizon); zs <- integer(horizon)
    zb[1L] <- z_ref; zs[1L] <- z_shock
    if (horizon > 1L) for (h in 2L:horizon) {
      zb[h] <- step_z(zb[h - 1L], u[h])
      ## "chain": each branch steps from its OWN state (Rosenblatt coupling).
      ## "common": the shocked branch inherits the baseline's realized state,
      ## so the realized log-TFP gap is exactly (Delta, 0, 0, ...).
      zs[h] <- if (continuation == "chain") step_z(zs[h - 1L], u[h]) else zb[h]
    }
    pb <- .hank_agg_simulate_path(sol, blk$a_grid, blk$Pi, blk$e,
                                  ks$alpha, ks$delta, obj$Z_grid,
                                  obj$K_grid, zb, D0, K0)
    ps <- .hank_agg_simulate_path(sol, blk$a_grid, blk$Pi, blk$e,
                                  ks$alpha, ks$delta, obj$Z_grid,
                                  obj$K_grid, zs, D0, K0)
    ## K chosen at date h is K[h + 1] in the path's indexing.
    dK[d, ] <- log(ps$K[-1L]) - log(pb$K[-1L])
    dZl[d, ] <- log(obj$Z_grid[zs]) - log(obj$Z_grid[zb])
    dC[d, ] <- log(ps$C) - log(pb$C)
    dY[d, ] <- log(ps$Y) - log(pb$Y)
    drr[d, ] <- ps$r - pb$r
    dww[d, ] <- log(ps$w) - log(pb$w)
  }
  delta_logZ <- log(obj$Z_grid[z_shock]) - log(obj$Z_grid[z_ref])
  m <- colMeans(dK)
  out_draws <- if (return_draws) list(dlogK_draws = dK, dlogZ_draws = dZl)
               else NULL
  c(list(dlogK = m, dlogK_scaled = m / delta_logZ,
       dlogC = colMeans(dC), dlogY = colMeans(dY),
       dr = colMeans(drr), dlogw = colMeans(dww),
       delta_logZ = delta_logZ,
       mcse = apply(dK, 2L, stats::sd) / sqrt(n_draws),
       dlogZ = colMeans(dZl),
       n_draws = n_draws, horizon = horizon, continuation = continuation,
       z_shock = z_shock, z_ref = z_ref), out_draws)
}


# =============================================================================
# Variance-free ergodic mean of aggregate capital  (F2-B)
# =============================================================================
#
# WHY THIS EXISTS. hank_ks_aggregate_risk() reports K_mean as the sample mean
# of ONE simulated aggregate path. That is fine for the rule fit (a slope,
# estimated from T observations of a highly informative regression) and
# useless for the AGGREGATE PRECAUTIONARY TERM, which is O(sd_Z^2): at
# sd_Z = 0.01 the shift is ~1e-4 of K, while the batch-means standard error of
# the mean of a series with rule slope ~0.94 over 800 retained periods is
# ~1e-3 of K. The reported sign of K_mean - K_ss was therefore noise.
#
# The fix is not a longer simulation (the error falls like T^{-1/2} against a
# fixed target, so resolving a 10x-smaller effect needs a 100x-longer run per
# solve) but removing the sampling entirely. The economy's state is
# (D, K, Z): D the household cross-section, K the predetermined aggregate
# capital, Z the aggregate state. Given the converged policies the map
#
#   (D, K, z) -> (D' = Push(D; a(K,z)), K' = <D, a(K,z)>, z' ~ Pi_Z[z, .])
#
# is a Markov chain whose ONLY randomness is z'. Iterating the DISTRIBUTION of
# that chain forward with Pi_Z -- rather than drawing a path from it -- gives
# E[K] with no Monte-Carlo error at all.
#
# The obstacle is that the (D, K) part is deterministic, so the number of
# distinct (D, K) atoms multiplies by n_z every period: after t periods there
# is one atom per Z-HISTORY. The standard cure (and the one used here) is
# state-space quantisation: fix a fine log-spaced grid K_fine, and after each
# push split each atom's mass between the two bracketing K_fine nodes with the
# usual linear (lottery) weights, merging atoms that land on the same node.
# Merging is a MIXTURE of cross-sections, and both the push and the
# aggregation are LINEAR in D, so the merge is exact in the D direction; the
# only approximation is that the merged atom's policy is read at the grid
# node rather than at its own K. The lottery split matches the conditional
# mean of log K exactly, so that error is O(h^2) in the bin width h, and the
# spurious quantisation variance it injects, <= h^2/4, is what the halving
# check in the tests bounds. (At n_fine = 101 over a 0.1-log-point span,
# h = 1e-3 and h^2/4 = 2.5e-7 against an ergodic Var(log K) of ~6e-5 -- three
# orders of magnitude of headroom.)
#
# COST. Everything is precomputed once per node: the policy, its savings
# lottery, and the scatter keys. One iteration is then one `rowsum` (the
# batched forward push over all n_fine*n_z nodes at once) plus two small
# mixes over Z, so the whole fixed point costs seconds, not minutes. The
# batched push is checked column-by-column against .hank_forward_push() in
# tests/testthat/test-hank-aggregate-risk-precautionary.R.


#' Per-node policies, savings lotteries and scatter keys on the fine K grid
#'
#' One entry per aggregate node \eqn{(K_{fine,j}, Z_z)}; the node index is
#' \code{(z - 1) * n_fine + j}, matching the \code{(K, Z)} stacking used by
#' \code{\link{.hank_agg_backward}}.
#'
#' @param obj A \code{hank_ks_agg_risk} object.
#' @param K_fine Increasing positive numeric: the fine aggregate-capital grid.
#' @return A list with \code{APOL}, \code{CPOL} (\code{(n_e*n_a) x n_node},
#'   distribution order), \code{KEY} and \code{LOTW} (\code{2*(n_e*n_a) x
#'   n_node} scatter keys and lottery weights for the batched push),
#'   \code{perm} (distribution order -> \code{n_e x n_a} column-major), and
#'   the dimensions.
#' @keywords internal
.hank_agg_ergodic_nodes <- function(obj, K_fine) {
  blk <- obj$ks$block
  a_grid <- blk$a_grid; e <- blk$e
  n_e <- length(e); n_a <- length(a_grid); n_ea <- n_e * n_a
  n_k <- length(obj$K_grid); n_z <- length(obj$Z_grid)
  n_fine <- length(K_fine); n_node <- n_fine * n_z
  log_K_grid <- log(obj$K_grid); log_Kf <- log(K_fine)

  APOL <- matrix(0, n_ea, n_node); CPOL <- matrix(0, n_ea, n_node)
  KEY  <- matrix(0L, 2L * n_ea, n_node); LOTW <- matrix(0, 2L * n_ea, n_node)
  off  <- (seq_len(n_e) - 1L) * n_a
  for (z in seq_len(n_z)) for (j in seq_len(n_fine)) {
    nd <- (z - 1L) * n_fine + j
    ap <- .hank_agg_policy_at(obj$policy$a_pol, log_K_grid, log_Kf[j], z,
                              n_e, n_a, n_k)
    cp <- .hank_agg_policy_at(obj$policy$c_pol, log_K_grid, log_Kf[j], z,
                              n_e, n_a, n_k)
    APOL[, nd] <- .hank_mat_to_vec(ap)
    CPOL[, nd] <- .hank_mat_to_vec(cp)
    lot <- .hank_lottery(ap, a_grid)
    KEY[, nd]  <- c(off + lot$i, off + lot$i + 1L) + (nd - 1L) * n_ea
    LOTW[, nd] <- c(lot$p, 1 - lot$p)
  }
  ## Distribution order is (e-1)*n_a + a; the lottery keys above are in the
  ## n_e x n_a matrix's own column-major order, so the push needs this
  ## permutation of the rows (and only the push does).
  perm <- as.integer(matrix(seq_len(n_ea), n_e, n_a, byrow = TRUE))
  list(APOL = APOL, CPOL = CPOL, KEY = KEY, LOTW = LOTW, perm = perm,
       n_e = n_e, n_a = n_a, n_ea = n_ea, n_fine = n_fine, n_z = n_z,
       n_node = n_node)
}


#' Batched Young forward push: one push per aggregate node, in one scatter
#'
#' Identical, column by column, to
#' \code{.hank_forward_push(a_pol_j, a_grid, Pi, D[, j])} -- the savings
#' lottery is precomputed by \code{\link{.hank_agg_ergodic_nodes}} and every
#' node's scatter is offset into one long accumulator, so the whole sweep is a
#' single \code{rowsum} plus an \code{n_e^2} block mix over income states
#' instead of \code{n_fine * n_z} separate calls.
#'
#' The columns need NOT be probability distributions: the push is linear in
#' \code{D}, so unnormalized (mass-weighted) columns are pushed correctly and
#' the caller never has to divide by a node probability.
#'
#' @param nodes A \code{\link{.hank_agg_ergodic_nodes}} object.
#' @param Pi Income transition matrix.
#' @param Dm Numeric \code{(n_e*n_a) x n_node}, distribution order.
#' @return A matrix of the same shape.
#' @keywords internal
.hank_agg_push_many <- function(nodes, Pi, Dm) {
  n_ea <- nodes$n_ea; n_e <- nodes$n_e; n_a <- nodes$n_a
  n_node <- ncol(Dm)
  Dc  <- Dm[nodes$perm, , drop = FALSE]
  W   <- rbind(Dc, Dc) * nodes$LOTW
  acc <- numeric(n_ea * n_node)
  s   <- rowsum(as.numeric(W), as.integer(nodes$KEY), reorder = FALSE)
  acc[as.integer(rownames(s))] <- s[, 1L]
  ## acc index is (nd-1)*n_ea + (e-1)*n_a + a', i.e. a fastest, then e, then
  ## the node: reshaping to n_a x (n_e*n_node) puts income state e in column
  ## e + (nd-1)*n_e, so mixing over income is n_e^2 whole-block operations.
  A   <- matrix(acc, n_a, n_e * n_node)
  out <- matrix(0, n_a, n_e * n_node)
  base <- (seq_len(n_node) - 1L) * n_e
  for (ep in seq_len(n_e)) {
    tmp <- NULL
    for (ee in seq_len(n_e)) {
      pr <- Pi[ee, ep]
      if (pr == 0) next
      b <- pr * A[, ee + base, drop = FALSE]
      tmp <- if (is.null(tmp)) b else tmp + b
    }
    if (!is.null(tmp)) out[, ep + base] <- tmp
  }
  matrix(out, n_ea, n_node)
}


#' Sampling-free ergodic mean of aggregate capital under aggregate risk
#'
#' Computes \eqn{E[K]}, \eqn{sd(K)} and the ergodic distribution of the
#' aggregate state of a solved \code{\link{hank_ks_aggregate_risk}} economy by
#' iterating the JOINT distribution of (household cross-section, aggregate
#' capital, aggregate state) forward with the aggregate chain's own transition
#' probabilities -- never by drawing a shock path. There is therefore no
#' Monte-Carlo error in the result, which is what makes the
#' \eqn{O(\sigma_Z^2)} aggregate precautionary term \eqn{E[K] - K_{ss}}
#' resolvable: the simulated \code{obj$K_mean} carries a batch-means standard
#' error an order of magnitude LARGER than that term, so its sign is not
#' identified (see
#' \code{tests/testthat/test-hank-aggregate-risk-precautionary.R}).
#'
#' @section Method:
#' Given the converged policies the state \eqn{(D, K, z)} evolves as
#' \eqn{D' = \mathrm{Push}(D; a(K, z))}, \eqn{K' = \langle D, a(K,z)\rangle},
#' \eqn{z' \sim \Pi_Z[z, \cdot]}, so the only randomness is \eqn{z'}. The
#' \eqn{(D, K)} part being deterministic, the number of atoms would multiply
#' by \eqn{n_z} each period (one per \eqn{Z}-history); the atoms are therefore
#' QUANTISED onto a fine log-spaced grid \code{K_fine}, each pushed atom
#' splitting between its two bracketing nodes with the usual linear weights
#' and atoms on the same node merging. Merging is a mixture of
#' cross-sections and both the push and the aggregation are linear in
#' \eqn{D}, so the merge is exact in the \eqn{D} direction; the approximation
#' is only that a merged atom's policy is read at the node rather than at its
#' own \eqn{K}, which the lottery split makes \eqn{O(h^2)} in the bin width
#' \eqn{h}. \strong{Always check the answer against a halved bin width} --
#' \code{n_fine = 2 * n_fine - 1} reuses every node -- and treat the
#' difference as the error bar.
#'
#' The reported \code{K_mean} is NOT the quantised node value: each node
#' carries the probability-weighted sum of the EXACT \eqn{K'} that landed on
#' it, so quantisation enters only through the policy argument.
#'
#' @param obj A \code{hank_ks_agg_risk} object from
#'   \code{\link{hank_ks_aggregate_risk}}.
#' @param n_fine Integer >= 3: number of fine aggregate-capital nodes,
#'   log-spaced across the span of \code{obj$K_grid}. Ignored when
#'   \code{K_fine} is supplied.
#' @param K_fine Optional explicit fine grid (increasing, positive).
#' @param tol Numeric: convergence tolerance on the RELATIVE change in the
#'   reported moments of \eqn{K} and \eqn{\log K} (see \code{gap}, and the
#'   note under \code{dist_gap}, in the return value).
#' @param maxit Integer: iteration cap on the forward distribution iteration.
#' @param verbose Logical: report progress every 100 iterations.
#'
#' @return A list with
#'   \describe{
#'     \item{\code{K_mean}, \code{K_sd}, \code{logK_mean}, \code{logK_sd}}{the
#'       ergodic moments of aggregate capital, free of sampling error.}
#'     \item{\code{K_ss}}{the deterministic reference \code{obj$ks$K}.}
#'     \item{\code{precautionary}}{\code{K_mean - K_ss}, and
#'       \code{precautionary_pct} in percent of \code{K_ss}.}
#'     \item{\code{C_mean}, \code{Y_mean}, \code{r_mean}}{ergodic means of
#'       aggregate consumption, output and the interest rate. \code{C_mean} is
#'       exact in the same sense as \code{K_mean}; \code{Y_mean} and
#'       \code{r_mean} are evaluated at the QUANTISED node capital (they are
#'       diagnostics, not the object of the test).}
#'     \item{\code{dist}}{\code{n_fine x n_z} ergodic distribution of the
#'       aggregate state.}
#'     \item{\code{D_mean}}{the ergodic average cross-section.}
#'     \item{\code{K_fine}, \code{bin_width}}{the quantisation grid and its
#'       spacing in log points.}
#'     \item{\code{mass_offgrid}}{probability mass whose \eqn{K'} fell outside
#'       \code{K_fine} and was clamped onto its boundary; must be 0 for the
#'       answer to mean anything.}
#'     \item{\code{iterations}, \code{converged}, \code{gap},
#'       \code{elapsed}}{iteration diagnostics. \code{gap} is the last
#'       relative change in the reported moments.}
#'     \item{\code{dist_gap}}{the last \code{max|dP|} over the aggregate-state
#'       distribution. This is NOT the convergence criterion and on a fine
#'       grid it need not go to zero: quantisation makes the bin assignment a
#'       step function of \eqn{K'}, so mass can settle into a small limit
#'       cycle across a bin edge. The cycle is of order the bin width and is
#'       bounded by the halving check; it does not move the moments (\code{gap}
#'       reaches double-precision zero in runs where \code{dist_gap} plateaus
#'       at ~2e-4).}
#'   }
#' @seealso \code{\link{hank_ks_aggregate_risk}}, \code{\link{hank_tfp_chain}}
#' @examples
#' \donttest{
#' inc    <- hank_income_rouwenhorst(rho = 0.95, sigma = 0.5, n = 3)
#' a_grid <- hank_asset_grid(amax = 50, n = 60, amin = 0)
#' ks     <- hank_ks_steady(a_grid, inc$Pi, inc$e, beta = 0.98, eis = 1,
#'                          alpha = 0.36, delta = 0.025)
#' fit <- hank_ks_aggregate_risk(ks, hank_tfp_chain(0.9, 0.01, 3L),
#'                               T_sim = 400L, burn_in = 100L, seed = 1L)
#' em  <- hank_ks_ergodic_mean(fit, n_fine = 51L)
#' c(simulated = fit$K_mean - fit$K_ss, exact = em$precautionary)
#' }
#' @export
hank_ks_ergodic_mean <- function(obj, n_fine = 101L, K_fine = NULL,
                                 tol = 1e-12, maxit = 5000L,
                                 verbose = FALSE) {
  if (!inherits(obj, "hank_ks_agg_risk"))
    stop("hank_ks_ergodic_mean(): 'obj' must be a hank_ks_aggregate_risk() ",
         "object (got class ", paste(class(obj), collapse = "/"), ").")
  t_start <- proc.time()[["elapsed"]]
  ks  <- obj$ks; blk <- ks$block
  Pi  <- blk$Pi; Pi_Z <- obj$Pi_Z; Z_grid <- obj$Z_grid
  alpha <- ks$alpha; delta <- ks$delta
  n_z <- length(Z_grid)

  if (is.null(K_fine)) {
    n_fine <- as.integer(n_fine)
    if (is.na(n_fine) || n_fine < 3L)
      stop("hank_ks_ergodic_mean(): 'n_fine' must be >= 3.")
    K_fine <- exp(seq(log(obj$K_grid[1L]),
                      log(obj$K_grid[length(obj$K_grid)]),
                      length.out = n_fine))
  }
  K_fine <- as.numeric(K_fine)
  n_fine <- length(K_fine)
  if (n_fine < 3L || any(diff(K_fine) <= 0) || any(K_fine <= 0))
    stop("hank_ks_ergodic_mean(): 'K_fine' must be a strictly increasing ",
         "vector of at least 3 positive values.")
  log_Kf <- log(K_fine)

  nodes <- .hank_agg_ergodic_nodes(obj, K_fine)
  n_ea <- nodes$n_ea; n_node <- nodes$n_node
  APOL <- nodes$APOL; CPOL <- nodes$CPOL

  ## --- initial condition: the deterministic cross-section, at the aggregate
  ## capital it clears, with Z drawn from the chain's stationary distribution.
  piZ <- if (n_z == 1L) 1 else .hank_stationary(Pi_Z)
  D0  <- blk$D; K0 <- blk$A
  w0  <- .hank_agg_K_weights(log_Kf, matrix(log(K0), 1L, 1L))
  j0  <- w0$i[1L, 1L]; wl0 <- min(max(w0$w[1L, 1L], 0), 1)
  P <- matrix(0, n_fine, n_z)
  for (z in seq_len(n_z)) {
    P[j0, z]      <- P[j0, z]      + piZ[z] * wl0
    P[j0 + 1L, z] <- P[j0 + 1L, z] + piZ[z] * (1 - wl0)
  }
  M <- matrix(0, n_ea, n_node)
  pv <- as.numeric(P)
  if (any(pv > 0)) M[, pv > 0] <- outer(D0, pv[pv > 0])
  S <- pv * K0; S2 <- pv * K0^2
  SL <- pv * log(K0); SL2 <- pv * log(K0)^2
  K_mean <- K0

  src_z  <- rep(seq_len(n_z), each = n_fine)
  z_base <- (src_z - 1L) * n_fine
  blk_j  <- seq_len(n_fine)
  ## Mix an (n_ea x n_node) unnormalized measure over Z with Pi_Z.
  mixZ <- function(G) {
    out <- matrix(0, n_ea, n_node)
    for (zp in seq_len(n_z)) {
      tmp <- NULL
      for (zz in seq_len(n_z)) {
        pr <- Pi_Z[zz, zp]
        if (pr == 0) next
        b <- pr * G[, (zz - 1L) * n_fine + blk_j, drop = FALSE]
        tmp <- if (is.null(tmp)) b else tmp + b
      }
      if (!is.null(tmp)) out[, (zp - 1L) * n_fine + blk_j] <- tmp
    }
    out
  }
  scat <- function(v, key) {
    out <- numeric(n_node)
    s <- rowsum(v, key, reorder = FALSE)
    out[as.integer(rownames(s))] <- s[, 1L]
    out
  }

  converged <- FALSE; gap <- Inf; dist_gap <- Inf; it <- 0L; mass_off <- 0
  mom <- c(K0, K0^2, log(K0), log(K0)^2)
  for (it in seq_len(maxit)) {
    pv <- as.numeric(P)
    ## K' at each node: <D, a(K_node, z)>. M is mass-weighted, so divide.
    num <- colSums(M * APOL)
    Kp <- ifelse(pv > 0, num / pmax(pv, .Machine$double.xmin), K_fine[j0])
    Kp[!is.finite(Kp) | Kp <= 0] <- K_fine[j0]
    Dp <- .hank_agg_push_many(nodes, Pi, M)

    wq  <- .hank_agg_K_weights(log_Kf, matrix(log(Kp), n_node, 1L))
    jlv <- wq$i[, 1L]; wraw <- wq$w[, 1L]
    wlv <- pmin(pmax(wraw, 0), 1)
    mass_off <- sum(pv[wraw < 0 | wraw > 1])

    ## Stage 1: scatter onto (source z, K bin).  Stage 2: mix over Z. Doing it
    ## in that order costs n_z^2 block operations instead of n_z scatters.
    key <- c(z_base + jlv, z_base + jlv + 1L)
    massv <- c(pv * wlv, pv * (1 - wlv))
    contrib <- cbind(Dp * rep(wlv, each = n_ea),
                     Dp * rep(1 - wlv, each = n_ea))
    g  <- rowsum(t(contrib), key, reorder = FALSE)
    G  <- matrix(0, n_ea, n_node)
    G[, as.integer(rownames(g))] <- t(g)

    Mn  <- mixZ(G)
    Pn   <- matrix(scat(massv, key), n_fine, n_z) %*% Pi_Z
    Kp2  <- c(Kp, Kp); lKp2 <- log(Kp2)
    Sn   <- matrix(scat(massv * Kp2, key), n_fine, n_z) %*% Pi_Z
    S2n  <- matrix(scat(massv * Kp2^2, key), n_fine, n_z) %*% Pi_Z
    SLn  <- matrix(scat(massv * lKp2, key), n_fine, n_z) %*% Pi_Z
    SL2n <- matrix(scat(massv * lKp2^2, key), n_fine, n_z) %*% Pi_Z

    ## CONVERGENCE IS DECLARED ON THE REPORTED MOMENTS, not on the joint
    ## distribution. Quantisation makes the bin assignment a STEP function of
    ## K', so on a fine grid the mass at individual nodes can settle into a
    ## small limit cycle (measured at n_fine = 201: max|dP| plateaus around
    ## 2e-4 forever) as an atom's K' sits astride a bin edge and its two
    ## neighbouring merged compositions alternate. That jitter is a
    ## quantisation artefact of order the bin width -- it is bounded by the
    ## halving check, not by iterating longer -- and it does NOT move the
    ## moments: the split is mean-preserving and each node carries the exact
    ## K' that landed on it, so |dE[K]|/E[K] reaches 0 (to double precision)
    ## by iteration ~200 in exactly the runs where max|dP| never does.
    ## Iterating to a distribution tolerance would therefore burn 20x the
    ## iterations and then fail anyway, on a criterion the answer does not
    ## depend on. max|dP| is still reported, as dist_gap.
    mom_new <- c(sum(Sn), sum(S2n), sum(SLn), sum(SL2n))
    gap <- max(abs(mom_new - mom) / pmax(abs(mom), 1))
    dist_gap <- max(abs(Pn - P))
    P <- Pn; M <- Mn; S <- Sn; S2 <- S2n; SL <- SLn; SL2 <- SL2n
    mom <- mom_new; K_mean <- mom_new[1L]
    if (verbose && (it %% 100L == 0L))
      message(sprintf(paste0("[hank_ks_ergodic_mean] iter %d  gap %.3e  ",
                             "dist_gap %.3e  E[K] %.10f"),
                      it, gap, dist_gap, K_mean))
    if (gap < tol) { converged <- TRUE; break }
  }
  if (!converged)
    warning("hank_ks_ergodic_mean(): the ergodic moments did not converge in ",
            maxit, " iterations (gap = ", format(gap), " vs tol = ",
            format(tol), ").", call. = FALSE)

  tot <- sum(P)
  K_mean  <- sum(S) / tot
  K_var   <- max(sum(S2) / tot - K_mean^2, 0)
  lK_mean <- sum(SL) / tot
  lK_var  <- max(sum(SL2) / tot - lK_mean^2, 0)
  C_mean  <- sum(colSums(M * CPOL)) / tot
  Knode <- rep(K_fine, times = n_z); Znode <- rep(Z_grid, each = n_fine)
  prc <- .hank_agg_prices(Knode, Znode, alpha, delta)
  Y_mean <- sum(as.numeric(P) * Znode * Knode^alpha) / tot
  r_mean <- sum(as.numeric(P) * prc$r) / tot

  list(K_mean = K_mean, K_sd = sqrt(K_var),
       logK_mean = lK_mean, logK_sd = sqrt(lK_var),
       K_ss = ks$K,
       precautionary = K_mean - ks$K,
       precautionary_pct = 100 * (K_mean / ks$K - 1),
       C_mean = C_mean, Y_mean = Y_mean, r_mean = r_mean,
       dist = P / tot, D_mean = rowSums(M) / tot,
       K_fine = K_fine, n_fine = n_fine,
       bin_width = diff(log_Kf)[1L],
       mass_offgrid = mass_off,
       iterations = it, converged = converged, gap = gap,
       dist_gap = dist_gap,
       elapsed = proc.time()[["elapsed"]] - t_start)
}
