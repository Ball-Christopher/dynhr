#' Krusell-Smith equilibrium WITH aggregate risk
#'
#' Solves the Krusell-Smith (1998) economy in which aggregate TFP is a
#' genuinely stochastic finite Markov chain, by the standard bounded-rationality
#' algorithm: households forecast next period's aggregate capital with a
#' log-linear rule (one intercept/slope pair per aggregate state), the implied
#' policies are simulated forward with the non-stochastic histogram method, and
#' the rule is re-fitted to the simulated law of motion until it stops moving.
#'
#' This is the first object in the HANK line that is NOT certainty-equivalent.
#' \code{\link{hank_ks_linear_irf}} and \code{\link{hank_ks_nonlinear_irf}}
#' both solve deterministic (perfect-foresight) paths off
#' \code{\link{hank_ks_steady}}; here the household's Euler equation integrates
#' over the aggregate shock as well as the idiosyncratic one, so the solution
#' carries aggregate precautionary effects and state-dependent dynamics. The
#' certainty-equivalent solution is recovered in the \eqn{\sigma_Z \to 0}
#' limit (asserted in
#' \code{tests/testthat/test-hank-aggregate-risk-oracle.R}).
#'
#' @section Algorithm:
#' \enumerate{
#'   \item BACKWARD. At every aggregate node \eqn{(K_k, Z_z)}, one EGM sweep
#'     with the continuation marginal value read at the forecast
#'     \eqn{K' = \exp(a_z + b_z \log K_k)} and averaged over \eqn{Z'} with
#'     \code{Pi_Z} (\code{\link{.hank_agg_backward}}). Interpolation in the
#'     aggregate state is linear in \eqn{\log K}.
#'   \item FORWARD. One long simulation of the DISTRIBUTION (Young's histogram
#'     method, \code{.hank_forward_push()}) under a drawn \eqn{Z} path;
#'     aggregate capital is the distribution's asset mean, so the law of motion
#'     is generated by the policies, not assumed.
#'   \item FIT. Regress \eqn{\log K_{t+1}} on \eqn{\log K_t} within each
#'     \eqn{Z} state; damp the update; repeat until the coefficients stop
#'     moving.
#' }
#' Every backward solve after the first is WARM-STARTED from the previous
#' iteration's marginal value array, which is what keeps the whole fixed point
#' to a few seconds rather than a few minutes.
#'
#' @param ks A \code{\link{hank_ks_steady}} steady state. It supplies the
#'   household calibration (\code{a_grid}, \code{Pi}, \code{e}, \code{beta},
#'   \code{eis}, \code{amin}), the firm calibration (\code{alpha},
#'   \code{delta}) and the deterministic reference point \code{K_ss}.
#' @param Z_grid Numeric length-\code{n_z} aggregate TFP levels, or a list as
#'   returned by \code{\link{hank_tfp_chain}} (in which case \code{Pi_Z} is
#'   taken from it). \code{Z_grid = 1} with \code{Pi_Z = matrix(1)} is the
#'   degenerate (no aggregate risk) chain.
#' @param Pi_Z Row-stochastic \code{n_z x n_z} aggregate transition matrix.
#' @param K_grid Optional aggregate-capital grid. \code{NULL} (default) sizes a
#'   log-spaced grid off the LINEAR model's implied stationary sd of
#'   \eqn{\log K} (see \code{\link{.hank_agg_default_K_grid}}).
#' @param n_k Integer: number of aggregate-capital nodes when \code{K_grid} is
#'   \code{NULL}.
#' @param rule_init Optional list with \code{a} and \code{b} (each length
#'   \code{n_z}) giving the initial forecast rule; defaults to
#'   \eqn{b_z = 0.9}, \eqn{a_z = (1 - 0.9)\log K_{ss}}.
#' @param damp Numeric in \eqn{(0, 1]}: weight on the newly fitted rule in the
#'   outer update.
#' @param tol Numeric: convergence tolerance on the max absolute change in the
#'   rule coefficients across outer iterations.
#' @param maxit Integer: outer-iteration cap.
#' @param egm_tol,egm_maxit Backward-sweep tolerance and iteration cap.
#' @param T_sim Integer: simulated periods per outer iteration.
#' @param burn_in Integer: periods discarded before fitting the rule and
#'   computing the reported ergodic moments.
#' @param seed Integer or \code{NULL}: seed for the aggregate shock path. The
#'   SAME path is reused across outer iterations (a common-random-numbers
#'   choice: it removes simulation noise from the fixed-point criterion, so
#'   \code{tol} measures rule movement, not resampling).
#' @param verbose Logical: report outer-iteration progress.
#'
#' @return An object of class \code{hank_ks_agg_risk}: a list with
#'   \describe{
#'     \item{\code{rule}}{list with \code{a}, \code{b} (length \code{n_z}),
#'       \code{R2} and \code{n_obs}.}
#'     \item{\code{den_haan}}{\code{max_pct} / \code{mean_pct}: the den Haan
#'       (2010) DYNAMIC forecast error in (approximate) percent.}
#'     \item{\code{policy}}{list with \code{a_pol}, \code{c_pol}, \code{Va}
#'       (each \code{(n_e*n_a) x (n_k*n_z)}), and \code{r_node},
#'       \code{w_node}.}
#'     \item{\code{ergodic}}{list with \code{dist} (an \code{n_k x n_z}
#'       frequency table of the aggregate state, built with the same
#'       lottery weights used to interpolate policies), \code{z_freq},
#'       \code{K_mean}, \code{K_sd}, \code{logK_mean}, \code{logK_sd},
#'       \code{D_mean} (the average cross-sectional distribution) and
#'       \code{D_sample} (post-burn-in distributions, used as
#'       \code{\link{hank_ks_risk_irf}}'s ergodic initial conditions).}
#'     \item{\code{K_mean}, \code{K_sd}}{Mean and sd of aggregate capital
#'       under aggregate risk, and \code{K_ss} the deterministic reference.}
#'     \item{\code{sim}}{the final simulated aggregate paths.}
#'     \item{\code{converged}, \code{iterations}, \code{rule_gap},
#'       \code{elapsed}}{fixed-point diagnostics.}
#'   }
#' @seealso \code{\link{hank_ks_risk_irf}}, \code{\link{hank_tfp_chain}},
#'   \code{\link{hank_ks_steady}}, \code{\link{hank_ks_linear_irf}}
#' @references Krusell, P. and A. A. Smith (1998), "Income and Wealth
#'   Heterogeneity in the Macroeconomy", JPE 106(5). den Haan, W. J. (2010),
#'   "Assessing the accuracy of the aggregate law of motion in models with
#'   heterogeneous agents", JEDC 34(1).
#' @examples
#' \donttest{
#' inc    <- hank_income_rouwenhorst(rho = 0.95, sigma = 0.5, n = 3)
#' a_grid <- hank_asset_grid(amax = 50, n = 60, amin = 0)
#' ks     <- hank_ks_steady(a_grid, inc$Pi, inc$e, beta = 0.98, eis = 1,
#'                          alpha = 0.36, delta = 0.025)
#' ch  <- hank_tfp_chain(rho = 0.9, sigma = 0.03, n = 3)
#' fit <- hank_ks_aggregate_risk(ks, ch, T_sim = 400L, burn_in = 100L,
#'                               seed = 1L)
#' fit$rule$R2
#' fit$den_haan$max_pct
#' }
#' @export
hank_ks_aggregate_risk <- function(ks, Z_grid, Pi_Z = NULL, K_grid = NULL,
                                   n_k = 7L, rule_init = NULL, damp = 0.5,
                                   tol = 1e-6, maxit = 60L,
                                   egm_tol = 1e-10, egm_maxit = 5000L,
                                   T_sim = 1500L, burn_in = 300L,
                                   seed = NULL, verbose = FALSE) {
  if (!inherits(ks, "hank_ks"))
    stop("hank_ks_aggregate_risk(): 'ks' must be a hank_ks_steady() object ",
         "(got class ", paste(class(ks), collapse = "/"), ").")
  if (is.list(Z_grid)) {
    if (is.null(Z_grid$Z_grid) || is.null(Z_grid$Pi_Z))
      stop("hank_ks_aggregate_risk(): a list 'Z_grid' must carry 'Z_grid' ",
           "and 'Pi_Z' (i.e. be a hank_tfp_chain() object).")
    if (!is.null(Pi_Z))
      stop("hank_ks_aggregate_risk(): 'Pi_Z' must be NULL when 'Z_grid' is a ",
           "hank_tfp_chain() object (it already carries the transition ",
           "matrix); passing both is ambiguous.")
    chain <- Z_grid
    Pi_Z <- chain$Pi_Z; Z_grid <- chain$Z_grid
  } else {
    chain <- NULL
  }
  Z_grid <- as.numeric(Z_grid)
  n_z <- length(Z_grid)
  if (n_z < 1L || any(!is.finite(Z_grid)) || any(Z_grid <= 0))
    stop("hank_ks_aggregate_risk(): 'Z_grid' must be finite and strictly ",
         "positive.")
  if (is.null(Pi_Z)) Pi_Z <- matrix(1, 1L, 1L)
  Pi_Z <- as.matrix(Pi_Z)
  .hank_check_markov(Pi_Z, n_z, caller = "hank_ks_aggregate_risk")
  if (!is.numeric(damp) || length(damp) != 1L || damp <= 0 || damp > 1)
    stop("hank_ks_aggregate_risk(): 'damp' must be a scalar in (0, 1].")
  T_sim <- as.integer(T_sim); burn_in <- as.integer(burn_in)
  if (burn_in >= T_sim)
    stop("hank_ks_aggregate_risk(): 'burn_in' (", burn_in, ") must be less ",
         "than 'T_sim' (", T_sim, ").")

  t_start <- proc.time()[["elapsed"]]
  blk <- ks$block
  a_grid <- blk$a_grid; Pi <- blk$Pi; e <- blk$e
  beta <- blk$beta; eis <- blk$eis; amin <- blk$amin
  alpha <- ks$alpha; delta <- ks$delta
  n_e <- length(e); n_a <- length(a_grid)

  ## --- aggregate capital grid -------------------------------------------
  sd_logK_linear <- NA_real_
  if (is.null(K_grid)) {
    rho_Z <- if (!is.null(chain)) chain$rho else .hank_agg_chain_rho(Pi_Z, Z_grid)
    sig_e <- if (!is.null(chain)) chain$sigma_eps
             else .hank_agg_chain_sigma_eps(Pi_Z, Z_grid)
    kg <- .hank_agg_default_K_grid(ks, sig_e, rho_Z, n_k = n_k)
    K_grid <- kg$K_grid
    sd_logK_linear <- kg$sd_logK
  }
  K_grid <- as.numeric(K_grid)
  n_k <- length(K_grid)
  if (n_k < 2L || any(diff(K_grid) <= 0) || any(K_grid <= 0))
    stop("hank_ks_aggregate_risk(): 'K_grid' must be a strictly increasing ",
         "vector of at least 2 positive values.")
  log_K_grid <- log(K_grid)

  ## --- initial rule ------------------------------------------------------
  if (is.null(rule_init)) {
    rule_b <- rep(0.9, n_z)
    rule_a <- (1 - rule_b) * log(ks$K)
  } else {
    rule_a <- as.numeric(rule_init$a); rule_b <- as.numeric(rule_init$b)
    if (length(rule_a) != n_z || length(rule_b) != n_z)
      stop("hank_ks_aggregate_risk(): 'rule_init$a' and 'rule_init$b' must ",
           "each have length n_z (", n_z, ").")
  }

  ## --- aggregate shock path (fixed across outer iterations) --------------
  if (!is.null(seed)) {
    if (!exists(".Random.seed", envir = globalenv(), inherits = FALSE)) {
      stats::runif(1)
    }
    old_seed <- get(".Random.seed", envir = globalenv(), inherits = FALSE)
    on.exit(assign(".Random.seed", old_seed, envir = globalenv()), add = TRUE)
    set.seed(as.integer(seed))
  }
  z0 <- if (n_z == 1L) 1L else as.integer(ceiling(n_z / 2))
  z_path <- .hank_agg_draw_z(Pi_Z, T_sim, z0)

  ## --- initial condition: the deterministic steady-state cross-section, and
  ## the aggregate capital it clears (blk$A == ks$K to the uniroot tolerance;
  ## blk$A is the household-side number, so the simulation starts EXACTLY on
  ## the household's own aggregate rather than on the firm's).
  D0 <- blk$D
  K0 <- blk$A

  Va_warm <- NULL
  converged <- FALSE; rule_gap <- Inf; it <- 0L
  sol <- NULL; sim <- NULL; fit <- NULL
  for (it in seq_len(maxit)) {
    sol <- .hank_agg_backward(a_grid, Pi, e, beta, eis, alpha, delta,
                              Z_grid, Pi_Z, K_grid, rule_a, rule_b,
                              amin = amin, Va_init = Va_warm,
                              tol = egm_tol, maxit = egm_maxit)
    if (!sol$converged)
      warning("hank_ks_aggregate_risk(): the backward EGM sweep did not ",
              "converge at outer iteration ", it, " (gap = ",
              format(sol$gap), " vs egm_tol = ", format(egm_tol), ").",
              call. = FALSE)
    Va_warm <- sol$Va
    sim <- .hank_agg_simulate_path(sol, a_grid, Pi, e, alpha, delta,
                                   Z_grid, K_grid, z_path, D0, K0,
                                   keep_D = TRUE)
    keep <- (burn_in + 1L):T_sim
    fit <- .hank_agg_fit_rule(log(sim$K[c(keep, T_sim + 1L)]),
                              z_path[keep], n_z)
    a_new <- ifelse(is.finite(fit$a), fit$a, rule_a)
    b_new <- ifelse(is.finite(fit$b), fit$b, rule_b)
    rule_gap <- max(abs(c(a_new - rule_a, b_new - rule_b)))
    rule_a <- (1 - damp) * rule_a + damp * a_new
    rule_b <- (1 - damp) * rule_b + damp * b_new
    if (verbose)
      message(sprintf("[hank_ks_aggregate_risk] iter %d  rule gap %.3e  R2 %s",
                      it, rule_gap,
                      paste(sprintf("%.5f", fit$R2), collapse = " ")))
    if (rule_gap < tol) { converged <- TRUE; break }
  }

  ## --- final pass on the converged rule ----------------------------------
  sol <- .hank_agg_backward(a_grid, Pi, e, beta, eis, alpha, delta,
                            Z_grid, Pi_Z, K_grid, rule_a, rule_b,
                            amin = amin, Va_init = Va_warm,
                            tol = egm_tol, maxit = egm_maxit)
  sim <- .hank_agg_simulate_path(sol, a_grid, Pi, e, alpha, delta,
                                 Z_grid, K_grid, z_path, D0, K0, keep_D = TRUE)
  keep <- (burn_in + 1L):T_sim
  logK_keep <- log(sim$K[c(keep, T_sim + 1L)])
  fit <- .hank_agg_fit_rule(logK_keep, z_path[keep], n_z)
  dh  <- .hank_agg_den_haan(logK_keep, z_path[keep], rule_a, rule_b)

  ## --- ergodic objects ---------------------------------------------------
  K_keep <- sim$K[keep]
  wk <- .hank_agg_K_weights(log_K_grid, matrix(log(K_keep), length(K_keep), 1L))
  erg <- matrix(0, n_k, n_z)
  zk <- z_path[keep]
  for (m in seq_along(K_keep)) {
    il <- wk$i[m, 1L]; wl <- min(max(wk$w[m, 1L], 0), 1)
    erg[il, zk[m]]      <- erg[il, zk[m]]      + wl
    erg[il + 1L, zk[m]] <- erg[il + 1L, zk[m]] + (1 - wl)
  }
  erg <- erg / sum(erg)
  z_freq <- tabulate(zk, nbins = n_z) / length(zk)
  D_sample <- sim$D[, keep, drop = FALSE]
  K_sample <- sim$K[keep]

  structure(list(
    ks = ks, Z_grid = Z_grid, Pi_Z = Pi_Z, K_grid = K_grid,
    chain = chain,
    rule = list(a = rule_a, b = rule_b, R2 = fit$R2, n_obs = fit$n_obs),
    den_haan = list(max_pct = dh$max_pct, mean_pct = dh$mean_pct),
    policy = list(a_pol = sol$a_pol, c_pol = sol$c_pol, Va = sol$Va,
                  r_node = sol$r_node, w_node = sol$w_node),
    ergodic = list(dist = erg, z_freq = z_freq,
                   K_mean = mean(K_keep), K_sd = stats::sd(K_keep),
                   logK_mean = mean(log(K_keep)),
                   logK_sd = stats::sd(log(K_keep)),
                   D_mean = rowMeans(D_sample), D_sample = D_sample,
                   K_sample = K_sample, z_sample = zk),
    K_mean = mean(K_keep), K_sd = stats::sd(K_keep), K_ss = ks$K,
    sd_logK_linear = sd_logK_linear,
    sim = list(K = sim$K, r = sim$r, w = sim$w, C = sim$C, Y = sim$Y,
               z_path = z_path, Z = Z_grid[z_path],
               frac_offgrid = sim$frac_offgrid),
    dims = c(n_e = n_e, n_a = n_a, n_k = n_k, n_z = n_z),
    egm = list(iterations = sol$iterations, converged = sol$converged,
               gap = sol$gap),
    converged = converged, iterations = it, rule_gap = rule_gap,
    T_sim = T_sim, burn_in = burn_in, seed = seed,
    elapsed = proc.time()[["elapsed"]] - t_start),
    class = "hank_ks_agg_risk")
}


#' Implied AR(1) persistence of a finite chain on log levels
#'
#' Least-squares persistence of \eqn{\log Z} under the chain's own stationary
#' distribution: \eqn{\rho = Cov(\log Z_{t+1}, \log Z_t) / Var(\log Z_t)}.
#' Used only to size the DEFAULT aggregate capital grid when the caller
#' supplies a raw \code{(Z_grid, Pi_Z)} pair rather than a
#' \code{\link{hank_tfp_chain}} object.
#' @param Pi_Z Row-stochastic transition.
#' @param Z_grid Level grid.
#' @return Numeric scalar (0 for a degenerate chain).
#' @keywords internal
.hank_agg_chain_rho <- function(Pi_Z, Z_grid) {
  if (length(Z_grid) < 2L) return(0)
  s  <- log(Z_grid)
  pz <- .hank_stationary(Pi_Z)
  m  <- sum(pz * s)
  v  <- sum(pz * (s - m)^2)
  if (v <= 0) return(0)
  cv <- sum(pz * (s - m) * (as.numeric(Pi_Z %*% s) - m))
  cv / v
}

#' Implied AR(1) innovation sd of a finite chain on log levels
#'
#' \eqn{\sigma_\varepsilon = \sigma \sqrt{1 - \rho^2}} with \eqn{\sigma} the
#' stationary sd of \eqn{\log Z} and \eqn{\rho} from
#' \code{\link{.hank_agg_chain_rho}}. Used only for the default K grid.
#' @param Pi_Z Row-stochastic transition.
#' @param Z_grid Level grid.
#' @return Numeric scalar (0 for a degenerate chain).
#' @keywords internal
.hank_agg_chain_sigma_eps <- function(Pi_Z, Z_grid) {
  if (length(Z_grid) < 2L) return(0)
  s  <- log(Z_grid)
  pz <- .hank_stationary(Pi_Z)
  m  <- sum(pz * s)
  sg <- sqrt(sum(pz * (s - m)^2))
  rho <- .hank_agg_chain_rho(Pi_Z, Z_grid)
  sg * sqrt(max(0, 1 - rho^2))
}


