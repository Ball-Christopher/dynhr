## R/hank-aggregate-risk.R
## --------------------------------------------------------------------------
## Krusell-Smith (1998) with AGGREGATE RISK.
##
## Everything else in the HANK line is certainty-equivalent: the sequence-space
## Jacobians (hank_ks_ge_jacobian / hank_ks_linear_irf) are linear
## perfect-foresight objects, and hank_ks_nonlinear_irf / hank_td_nonlinear
## solve a DETERMINISTIC transition path.  Neither knows that the aggregate
## state is random, so neither can price aggregate risk or produce a
## state-dependent impulse response.
##
## This file adds the genuine aggregate-uncertainty solution for the SAME
## Krusell-Smith economy that hank_ks_steady() calibrates:
##
##   aggregate TFP  log Z_t  is a finite Markov chain (Z_grid, Pi_Z)
##   aggregate state (K, Z)  with K = beginning-of-period aggregate capital
##   firm            r(K, Z) = alpha Z K^(alpha-1) - delta
##                   w(K, Z) = (1 - alpha) Z K^alpha
##   household       EGM on the asset grid, with the continuation value read
##                   off the aggregate grid at the FORECAST K'
##   forecast rule   log K' = a_z + b_z log K            (one pair per Z state)
##   equilibrium     the rule reproduces the law of motion generated by the
##                   household policies it implies (Krusell-Smith fixed point)
##
## Timing convention (identical to R/hank-ge.R so the two are directly
## comparable): K entering period t is PREDETERMINED and prices at t are
## r_t = alpha Z_t K_t^(alpha-1) - delta.  In the sequence-space notation of
## hank_ks_linear_irf(), which indexes K by the date it is CHOSEN, the object
## called dK[h] there is the response of this file's K_{h+1}.  The oracle
## tests line the two up explicitly.
##
## Distribution dynamics use the NON-STOCHASTIC histogram method (Young 2010)
## already in R/hank-distribution.R (.hank_forward_push): the cross-sectional
## distribution is pushed forward by the policy, never simulated agent by
## agent, so the only Monte-Carlo noise anywhere is in the AGGREGATE shock
## path.
##
## Interpolation in the aggregate capital state is LINEAR IN log K (the same
## variable the forecast rule is linear in), on a log-spaced K grid.  Linear
## rather than Chebyshev: the policy is close to log-linear in K over the
## ergodic set, a piecewise-linear interpolant reproduces its SLOPE to
## O(h^2) on a smooth function, and the resulting operator is a fixed sparse
## matrix that can be applied to the whole (n_e*n_a) x (n_k*n_z) value array
## in a single matmul (see .hank_agg_expectation_operator).
## --------------------------------------------------------------------------


# =============================================================================
# Aggregate TFP chain
# =============================================================================

#' Discretize an AR(1) aggregate TFP process into a finite Markov chain
#'
#' Rouwenhorst (1995) discretization of
#' \deqn{\log Z_t = \rho \log Z_{t-1} + \varepsilon_t, \qquad
#'       \varepsilon_t \sim (0, \sigma_\varepsilon^2),}
#' parameterized by the STATIONARY standard deviation
#' \eqn{\sigma = \sigma_\varepsilon / \sqrt{1 - \rho^2}} (the same convention
#' as \code{\link{hank_income_rouwenhorst}}).
#'
#' The Rouwenhorst transition matrix itself is built by the package's existing
#' helper (\code{.hank_rouwenhorst_Pi}, R/hank-income.R) -- there is exactly
#' one Rouwenhorst implementation in dynhr.  The only difference from
#' \code{hank_income_rouwenhorst} is the LEVEL normalization: an idiosyncratic
#' efficiency process is rescaled so that \eqn{E[e] = 1} (labour supply is a
#' normalization), whereas aggregate TFP is a level with economic content and
#' is left as \eqn{Z = \exp(s)} with \eqn{E[\log Z] = 0}, so that the
#' deterministic steady state \eqn{Z = 1} is the \eqn{\sigma \to 0} limit of
#' the chain and \code{\link{hank_ks_steady}} is the certainty-equivalent
#' reference point.
#'
#' Two properties of Rouwenhorst that the oracles in
#' \code{tests/testthat/test-hank-aggregate-risk-oracle.R} rely on:
#' \itemize{
#'   \item the conditional mean is EXACTLY the AR(1) one,
#'     \eqn{E[s_{t+1} \mid s_t] = \rho s_t}, for every \code{n}; and
#'   \item the stationary variance is exactly \eqn{\sigma^2} for every
#'     \code{n} (so an \code{n = 2} and an \code{n = 5} chain target the same
#'     AR(1) and may be compared directly).
#' }
#'
#' @param rho Numeric in \eqn{(-1, 1)}: AR(1) persistence of \eqn{\log Z}.
#' @param sigma Numeric > 0: STATIONARY standard deviation of \eqn{\log Z}.
#'   Pass \code{sigma = sigma_eps / sqrt(1 - rho^2)} to target an innovation
#'   standard deviation.
#' @param n Integer >= 2: number of aggregate states.
#'
#' @return A list with \code{Z_grid} (length \code{n}, increasing, strictly
#'   positive), \code{Pi_Z} (\code{n x n} row-stochastic), \code{pi_Z} (the
#'   stationary distribution), \code{log_Z} (the log grid), and the
#'   calibration \code{rho}, \code{sigma}, \code{sigma_eps}, \code{n}.
#' @seealso \code{\link{hank_ks_aggregate_risk}},
#'   \code{\link{hank_income_rouwenhorst}}
#' @examples
#' ch <- hank_tfp_chain(rho = 0.9, sigma = 0.03, n = 5)
#' round(ch$Z_grid, 4)
#' ## Rouwenhorst matches the AR(1) conditional mean exactly:
#' max(abs(as.numeric(ch$Pi_Z %*% ch$log_Z) - ch$rho * ch$log_Z))
#' @export
hank_tfp_chain <- function(rho, sigma, n = 5L) {
  n <- as.integer(n)
  if (!is.finite(rho) || abs(rho) >= 1)
    stop("hank_tfp_chain(): 'rho' must be finite and in (-1, 1).")
  if (!is.finite(sigma) || sigma <= 0)
    stop("hank_tfp_chain(): 'sigma' must be a finite positive number (the ",
         "STATIONARY sd of log Z).")
  if (n < 2L)
    stop("hank_tfp_chain(): 'n' must be >= 2. For a degenerate (no aggregate ",
         "risk) chain pass Z_grid = 1 and Pi_Z = matrix(1) directly to ",
         "hank_ks_aggregate_risk().")
  p    <- (1 + rho) / 2
  Pi_Z <- .hank_rouwenhorst_Pi(n, p)
  piZ  <- .hank_stationary(Pi_Z)
  s0    <- seq(-1, 1, length.out = n)
  mean0 <- sum(piZ * s0)
  var0  <- sum(piZ * (s0 - mean0)^2)
  s     <- (s0 - mean0) * (sigma / sqrt(var0))
  list(Z_grid = exp(s), Pi_Z = Pi_Z, pi_Z = piZ, log_Z = s,
       rho = rho, sigma = sigma, sigma_eps = sigma * sqrt(1 - rho^2), n = n)
}


# =============================================================================
# Internals: aggregate-state grids, prices, expectation operator
# =============================================================================

#' Firm prices at an aggregate state
#'
#' \eqn{r = \alpha Z K^{\alpha-1} - \delta}, \eqn{w = (1-\alpha) Z K^{\alpha}},
#' with \eqn{K} the PREDETERMINED beginning-of-period aggregate capital (the
#' same closure as \code{\link{hank_ks_steady}} and
#' \code{\link{hank_ks_ge_jacobian}}).
#' @param K,Z Numeric (recycled against each other by \code{outer}-style ops).
#' @param alpha,delta Capital share and depreciation.
#' @return A list with \code{r} and \code{w}.
#' @keywords internal
.hank_agg_prices <- function(K, Z, alpha, delta) {
  list(r = alpha * Z * K^(alpha - 1) - delta,
       w = (1 - alpha) * Z * K^alpha)
}


#' Default aggregate-capital grid, sized off the LINEAR model
#'
#' The ergodic spread of \eqn{\log K} is not known before the model is solved,
#' so the default grid is sized from the certainty-equivalent (sequence-space)
#' solution, which is available for free: feed the AR(1) TFP impulse into
#' \code{\link{hank_ks_linear_irf}} to get the MA coefficients
#' \eqn{\psi_h = d\log K_{h}/d\varepsilon} and read off
#' \eqn{sd(\log K) = \sigma_\varepsilon \sqrt{\sum_h \psi_h^2}}.
#' The grid then spans \code{n_sd} stationary standard deviations either side
#' of \eqn{\log K_{ss}}, with a floor (\code{min_span}) so that a degenerate
#' or near-degenerate chain still gets a non-trivial, well-conditioned grid.
#'
#' @param ks A \code{\link{hank_ks_steady}} steady state.
#' @param sigma_eps Innovation sd of \eqn{\log Z} (0 for a degenerate chain).
#' @param rho Persistence of \eqn{\log Z}.
#' @param n_k Integer >= 2: number of aggregate-capital nodes.
#' @param n_sd Numeric: half-width in stationary sd of \eqn{\log K}.
#' @param min_span Numeric: floor on the half-width in log points.
#' @param T_h Integer: horizon used for the MA truncation.
#' @return A list with \code{K_grid} (increasing, log-spaced) and
#'   \code{sd_logK} (the linear-model stationary sd used to size it).
#' @keywords internal
.hank_agg_default_K_grid <- function(ks, sigma_eps, rho, n_k = 7L, n_sd = 4,
                                     min_span = 0.01, T_h = 200L) {
  sd_logK <- 0
  if (sigma_eps > 0) {
    ## AR(1) impulse of size 1 in log Z at date 1: dZ_h = Z_ss * rho^(h-1).
    dZ  <- ks$Z * rho^(seq_len(T_h) - 1L)
    irf <- hank_ks_linear_irf(ks, dZ)
    psi <- irf$dK / ks$K
    sd_logK <- sigma_eps * sqrt(sum(psi^2))
  }
  span <- max(n_sd * sd_logK, min_span)
  list(K_grid = exp(seq(log(ks$K) - span, log(ks$K) + span,
                        length.out = as.integer(n_k))),
       sd_logK = sd_logK)
}


#' Linear-in-log-K interpolation weights onto a log-spaced K grid
#'
#' Returns the lower bracketing index (clamped to \code{[1, n_k - 1]}) and the
#' weight on it.  Outside the grid the weights are NOT clamped, so the
#' interpolant extrapolates linearly with the nearest interval's slope --
#' matching \code{\link{.hank_interp1}}'s convention rather than flattening
#' the policy at the boundary (a flat extrapolation would create a spurious
#' kink exactly where the simulated path is least well covered).
#'
#' @param log_K_grid Increasing numeric: \code{log(K_grid)}.
#' @param log_Kq Numeric query points in logs.
#' @return A list with \code{i} (integer, same shape as \code{log_Kq}) and
#'   \code{w} (weight on node \code{i}; \code{1 - w} on \code{i + 1}).
#' @keywords internal
.hank_agg_K_weights <- function(log_K_grid, log_Kq) {
  n_k <- length(log_K_grid)
  if (n_k < 2L)
    stop(".hank_agg_K_weights(): the aggregate capital grid needs >= 2 nodes.")
  i <- findInterval(log_Kq, log_K_grid)
  i[i < 1L] <- 1L
  i[i > n_k - 1L] <- n_k - 1L
  dim(i) <- dim(log_Kq)
  lo <- log_K_grid[i]; hi <- log_K_grid[i + 1L]
  w  <- (hi - log_Kq) / (hi - lo)
  dim(w) <- dim(log_Kq)
  list(i = i, w = w)
}


#' Aggregate expectation operator for the backward EGM sweep
#'
#' Builds the \code{(n_k*n_z) x (n_k*n_z)} matrix \code{W} such that, with the
#' marginal-value array stored as a \code{(n_e*n_a) x (n_k*n_z)} matrix
#' \code{M} (column \code{(z-1)*n_k + k} holding \eqn{V_a(\cdot;K_k,Z_z)}),
#' \deqn{(M W)[\cdot, (z-1)n_k + k]
#'   = \sum_{z'} \Pi_Z[z, z']\, V_a(\cdot; K'(K_k, Z_z), Z_{z'}),}
#' i.e. one dense matmul does BOTH the aggregate expectation and the
#' interpolation of the continuation value at the forecast \eqn{K'}.
#'
#' The operator depends only on the forecast rule and the grids, not on the
#' iterate, so it is built once per backward solve and reused every backward
#' iteration.  (This is why the backward sweep costs one small matmul plus
#' \code{n_k*n_z} EGM steps per iteration, and not \code{n_k*n_z*n_z}
#' interpolations.)
#'
#' @param log_K_grid Increasing numeric \code{log(K_grid)}.
#' @param Pi_Z Row-stochastic \code{n_z x n_z} aggregate transition.
#' @param log_Kp Numeric \code{n_k x n_z}: \eqn{\log K'} implied by the rule.
#' @return A \code{(n_k*n_z) x (n_k*n_z)} numeric matrix.
#' @keywords internal
.hank_agg_expectation_operator <- function(log_K_grid, Pi_Z, log_Kp) {
  n_k <- length(log_K_grid); n_z <- nrow(Pi_Z)
  wk  <- .hank_agg_K_weights(log_K_grid, log_Kp)
  W   <- matrix(0, n_k * n_z, n_k * n_z)
  for (z in seq_len(n_z)) {
    for (k in seq_len(n_k)) {
      col <- (z - 1L) * n_k + k
      il  <- wk$i[k, z]; wl <- wk$w[k, z]
      for (zp in seq_len(n_z)) {
        pr <- Pi_Z[z, zp]
        if (pr == 0) next
        base <- (zp - 1L) * n_k
        W[base + il,      col] <- W[base + il,      col] + pr * wl
        W[base + il + 1L, col] <- W[base + il + 1L, col] + pr * (1 - wl)
      }
    }
  }
  W
}


#' Backward EGM sweep on the (a, e) x (K, Z) state space
#'
#' Iterates the SAME one-asset EGM kernel used by \code{\link{hank_egm_solve}}
#' (\code{\link{.hank_egm_step}}) at every aggregate node \code{(K_k, Z_z)},
#' with the continuation value supplied by
#' \code{\link{.hank_agg_expectation_operator}}.  Because idiosyncratic
#' \eqn{e'} and aggregate \eqn{Z'} are independent, the double expectation
#' factors: the \eqn{Z'} average is taken first (by the operator) and
#' \code{.hank_egm_step}'s own \code{Pi \%*\% Va_p} then takes the \eqn{e'}
#' average, so the kernel is reused verbatim rather than reimplemented.
#'
#' @param a_grid,Pi,e,beta,eis Household calibration (as
#'   \code{\link{hank_het_block}}).
#' @param alpha,delta Firm calibration.
#' @param Z_grid,Pi_Z Aggregate chain.
#' @param K_grid Aggregate capital grid (increasing, positive).
#' @param rule_a,rule_b Length-\code{n_z} forecast-rule coefficients,
#'   \eqn{\log K' = a_z + b_z \log K}.
#' @param amin Borrowing constraint.
#' @param Va_init Optional \code{(n_e*n_a) x (n_k*n_z)} warm start.
#' @param tol,maxit Convergence tolerance on the savings policy, iteration cap.
#' @return A list with \code{Va}, \code{a_pol}, \code{c_pol} (each
#'   \code{(n_e*n_a) x (n_k*n_z)}, column-major within the \code{n_e x n_a}
#'   block), \code{r_node}, \code{w_node} (\code{n_k x n_z}),
#'   \code{iterations}, \code{converged}, \code{gap}.
#' @keywords internal
.hank_agg_backward <- function(a_grid, Pi, e, beta, eis, alpha, delta,
                               Z_grid, Pi_Z, K_grid, rule_a, rule_b,
                               amin = NULL, Va_init = NULL,
                               tol = 1e-10, maxit = 5000L) {
  n_e <- length(e); n_a <- length(a_grid)
  n_k <- length(K_grid); n_z <- length(Z_grid)
  if (is.null(amin)) amin <- a_grid[1L]
  log_K <- log(K_grid)
  log_Kp <- outer(log_K, rule_b, "*") + rep(rule_a, each = n_k)  # n_k x n_z
  W <- .hank_agg_expectation_operator(log_K, Pi_Z, log_Kp)

  pr <- .hank_agg_prices(matrix(K_grid, n_k, n_z),
                         matrix(Z_grid, n_k, n_z, byrow = TRUE), alpha, delta)
  r_node <- pr$r; w_node <- pr$w
  n_node <- n_k * n_z

  if (is.null(Va_init)) {
    M <- matrix(0, n_e * n_a, n_node)
    for (z in seq_len(n_z)) for (k in seq_len(n_k)) {
      j <- (z - 1L) * n_k + k
      coh0 <- (1 + r_node[k, z]) * matrix(a_grid, n_e, n_a, byrow = TRUE) +
        w_node[k, z] * e
      M[, j] <- as.numeric((1 + r_node[k, z]) *
                             pmax(0.1 * coh0, 1e-12)^(-1 / eis))
    }
  } else {
    M <- Va_init
  }

  A_old <- matrix(-Inf, n_e * n_a, n_node)
  A_new <- matrix(0, n_e * n_a, n_node)
  C_new <- matrix(0, n_e * n_a, n_node)
  M_new <- matrix(0, n_e * n_a, n_node)
  converged <- FALSE; gap <- NA_real_; it <- 0L
  for (it in seq_len(maxit)) {
    EM <- M %*% W
    for (z in seq_len(n_z)) for (k in seq_len(n_k)) {
      j <- (z - 1L) * n_k + k
      st <- .hank_egm_step(matrix(EM[, j], n_e, n_a), a_grid,
                           y = w_node[k, z] * e, r = r_node[k, z],
                           beta = beta, eis = eis, Pi = Pi, amin = amin)
      M_new[, j] <- as.numeric(st$Va)
      A_new[, j] <- as.numeric(st$a)
      C_new[, j] <- as.numeric(st$c)
    }
    gap <- max(abs(A_new - A_old))
    M <- M_new; A_old <- A_new
    if (gap < tol) { converged <- TRUE; break }
  }
  list(Va = M, a_pol = A_new, c_pol = C_new,
       r_node = r_node, w_node = w_node,
       iterations = it, converged = converged, gap = gap)
}


#' Interpolate a stacked policy array in log K at one aggregate state
#'
#' @param P Numeric \code{(n_e*n_a) x (n_k*n_z)} policy array.
#' @param log_K_grid Increasing \code{log(K_grid)}.
#' @param log_K Scalar query in logs.
#' @param z Integer aggregate-state index.
#' @param n_e,n_a Household grid dimensions.
#' @param n_k Number of aggregate-capital nodes.
#' @return An \code{n_e x n_a} matrix.
#' @keywords internal
.hank_agg_policy_at <- function(P, log_K_grid, log_K, z, n_e, n_a, n_k) {
  wk <- .hank_agg_K_weights(log_K_grid, matrix(log_K, 1L, 1L))
  il <- wk$i[1L, 1L]; wl <- wk$w[1L, 1L]
  base <- (z - 1L) * n_k
  matrix(wl * P[, base + il] + (1 - wl) * P[, base + il + 1L], n_e, n_a)
}


#' One aggregate simulation of the distribution under a given Z-index path
#'
#' Non-stochastic histogram simulation: the cross-section is pushed forward by
#' \code{.hank_forward_push()}, never sampled.
#'
#' @param sol Backward solution from \code{\link{.hank_agg_backward}}.
#' @param a_grid,Pi,e,alpha,delta,Z_grid,K_grid Model objects.
#' @param z_path Integer vector of aggregate-state indices, length \code{T}.
#' @param D0 Initial distribution (length \code{n_e*n_a}, distribution order).
#' @param K0 Aggregate capital ENTERING period 1 (see Details).
#' @param keep_D Logical: also return the per-period distributions.
#'
#' @details
#' Aggregate capital is measured as \code{hank_aggregate(D_t, a_pol_t)} --
#' mass-weighted household SAVINGS -- which is the same quantity
#' \code{\link{hank_het_block}} reports as \code{A} and the same one
#' \code{\link{hank_ks_steady}} clears against the firm's capital demand. It
#' is NOT \code{sum(D_{t+1} * a_grid)}: Young's savings lottery preserves the
#' conditional mean only for policies strictly inside the grid, so at the top
#' of a finite asset grid the two differ (by 0.5\% on the small example grid
#' used in the tests). Using the distribution-mean version would silently
#' define a DIFFERENT aggregate from the one the sequence-space Jacobians
#' differentiate, and the certainty-equivalence limit against
#' \code{\link{hank_ks_linear_irf}} would then be off by that wedge no matter
#' how fine the aggregate grid -- which is exactly how this was caught.
#'
#' @return A list with \code{K} (length \code{T + 1}: \code{K[t]} is the
#'   capital entering period \code{t}, so \code{K[T+1]} is the capital chosen
#'   in the last simulated period), \code{r}, \code{w}, \code{C}, \code{Y}
#'   (length \code{T}), \code{D_last}, and \code{frac_offgrid}.
#' @keywords internal
.hank_agg_simulate_path <- function(sol, a_grid, Pi, e, alpha, delta,
                                    Z_grid, K_grid, z_path, D0, K0,
                                    keep_D = FALSE) {
  n_e <- length(e); n_a <- length(a_grid); n_k <- length(K_grid)
  Tn <- length(z_path)
  log_K_grid <- log(K_grid)
  D <- D0
  Kv <- numeric(Tn + 1L); rv <- numeric(Tn); wv <- numeric(Tn)
  Cv <- numeric(Tn); Yv <- numeric(Tn)
  Dstore <- if (keep_D) matrix(0, length(D0), Tn) else NULL
  off <- 0L
  lo <- log_K_grid[1L]; hi <- log_K_grid[n_k]
  K <- K0
  for (t in seq_len(Tn)) {
    Kv[t] <- K
    if (keep_D) Dstore[, t] <- D
    lK <- log(K)
    if (lK < lo || lK > hi) off <- off + 1L
    z <- z_path[t]
    Zt <- Z_grid[z]
    pr <- .hank_agg_prices(K, Zt, alpha, delta)
    rv[t] <- pr$r; wv[t] <- pr$w
    Yv[t] <- Zt * K^alpha
    a_pol <- .hank_agg_policy_at(sol$a_pol, log_K_grid, lK, z, n_e, n_a, n_k)
    c_pol <- .hank_agg_policy_at(sol$c_pol, log_K_grid, lK, z, n_e, n_a, n_k)
    Cv[t] <- hank_aggregate(D, c_pol)
    K <- hank_aggregate(D, a_pol)
    D <- .hank_forward_push(a_pol, a_grid, Pi, D)
  }
  Kv[Tn + 1L] <- K
  list(K = Kv, r = rv, w = wv, C = Cv, Y = Yv, D_last = D, D = Dstore,
       frac_offgrid = off / Tn)
}


#' Fit the per-Z log-linear forecast rule to a simulated path
#'
#' Regresses \eqn{\log K_{t+1}} on \eqn{\log K_t} separately within each
#' aggregate state \code{z_t}.  A state whose realized \eqn{\log K_t} has
#' a standard deviation below \code{1e-8} log points -- which is exactly what
#' a degenerate chain produces, since the simulation then converges to a
#' point -- gets the
#' DEGENERATE rule \eqn{b_z = 0}, \eqn{a_z = \overline{\log K_{t+1}}} and
#' \code{R2 = NA}: a slope is not identified there, and inventing one (or
#' inheriting the previous iteration's) would silently make the household
#' forecast off a number the data never spoke to.
#'
#' @param logK Numeric length \code{T + 1}: realized \eqn{\log K_t}.
#' @param z_path Integer length \code{T}.
#' @param n_z Number of aggregate states.
#' @return A list with \code{a}, \code{b}, \code{R2}, \code{n_obs} (each
#'   length \code{n_z}).
#' @keywords internal
.hank_agg_fit_rule <- function(logK, z_path, n_z) {
  a <- numeric(n_z); b <- numeric(n_z)
  R2 <- rep(NA_real_, n_z); n_obs <- integer(n_z)
  x_all <- logK[seq_along(z_path)]
  y_all <- logK[seq_along(z_path) + 1L]
  for (z in seq_len(n_z)) {
    sel <- which(z_path == z)
    n_obs[z] <- length(sel)
    if (length(sel) == 0L) { a[z] <- NA_real_; b[z] <- NA_real_; next }
    x <- x_all[sel]; y <- y_all[sel]
    xb <- mean(x); yb <- mean(y)
    sxx <- sum((x - xb)^2)
    ## Flat test on the SD OF A LOG, i.e. already a relative criterion, and
    ## set well above double-precision noise (1e-8 log points = 1e-6 percent
    ## of K). A tighter, purely-numerical threshold is worse than useless
    ## here: on a degenerate chain the simulated log K settles to ~1e-11
    ## dispersion, which is not "no variance" in floating point, so the
    ## regression happily fits a slope to ROUNDING NOISE, the slope is
    ## different every outer iteration, and the fixed point never converges
    ## even though K itself is pinned to 11 digits.
    if (!is.finite(sxx) || sqrt(sxx / length(sel)) < 1e-8) {
      b[z] <- 0; a[z] <- yb; R2[z] <- NA_real_
    } else {
      bz <- sum((x - xb) * (y - yb)) / sxx
      b[z] <- bz; a[z] <- yb - bz * xb
      sst <- sum((y - yb)^2)
      R2[z] <- if (sst > 0) 1 - sum((y - a[z] - bz * x)^2) / sst else NA_real_
    }
  }
  list(a = a, b = b, R2 = R2, n_obs = n_obs)
}


#' den Haan (2010) dynamic forecast accuracy of a Krusell-Smith rule
#'
#' The one-step \eqn{R^2} of a KS forecast rule is famously uninformative;
#' den Haan's diagnostic iterates the rule forward from a SINGLE initial
#' condition over the whole simulated sample, feeding it only the realized
#' aggregate-shock path, and compares that dynamic forecast with the
#' simulated series.
#'
#' @param logK Numeric length \code{T + 1}: realized \eqn{\log K_t}.
#' @param z_path Integer length \code{T}.
#' @param rule_a,rule_b Rule coefficients.
#' @return A list with \code{max_pct}, \code{mean_pct} (100 * absolute log
#'   deviation, i.e. approximate percent) and the forecast path \code{logK_hat}.
#' @keywords internal
.hank_agg_den_haan <- function(logK, z_path, rule_a, rule_b) {
  Tn <- length(z_path)
  hat <- numeric(Tn + 1L)
  hat[1L] <- logK[1L]
  for (t in seq_len(Tn))
    hat[t + 1L] <- rule_a[z_path[t]] + rule_b[z_path[t]] * hat[t]
  err <- 100 * abs(logK - hat)
  list(max_pct = max(err), mean_pct = mean(err), logK_hat = hat)
}


#' Draw an aggregate-state index path from a finite Markov chain
#' @param Pi_Z Row-stochastic transition.
#' @param Tn Integer path length.
#' @param z0 Integer starting state index.
#' @param u Optional length-\code{Tn} vector of uniforms (common random
#'   numbers); drawn if \code{NULL}.
#' @return An integer vector of length \code{Tn}.
#' @keywords internal
.hank_agg_draw_z <- function(Pi_Z, Tn, z0, u = NULL) {
  n_z <- nrow(Pi_Z)
  if (n_z == 1L) return(rep(1L, Tn))
  if (is.null(u)) u <- stats::runif(Tn)
  cdf <- t(apply(Pi_Z, 1L, cumsum))
  z <- integer(Tn)
  cur <- z0
  for (t in seq_len(Tn)) {
    cur <- as.integer(1L + sum(cdf[cur, ] < u[t]))
    if (cur > n_z) cur <- n_z
    z[t] <- cur
  }
  z
}


